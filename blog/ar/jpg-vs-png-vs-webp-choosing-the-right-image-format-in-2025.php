    <h2>JPG (أو JPEG): ملك الصور الفوتوغرافية</h2>
    <p>JPG، الذي يرمز إلى Joint Photographic Experts Group، هو تنسيق الصور الأكثر شيوعًا على الإنترنت، ولسبب وجيه. إنه الخيار المفضل لأي نوع من الصور الفوتوغرافية المعقدة.</p>
    <ul>
        <li><strong>الأفضل لـ:</strong> الصور الفوتوغرافية، والصور ذات التدرجات اللونية المعقدة، والصور الواقعية.</li>
        <li><strong>الضغط:</strong> يستخدم JPG ضغط "مع فقدان البيانات". هذا يعني أنه عند حفظ صورة بتنسيق JPG، فإنه يتخلص بذكاء من بعض بيانات الصورة لجعل حجم الملف أصغر بكثير. يمكنك عادةً اختيار مستوى الضغط (على سبيل المثال، من 0 إلى 100). تعني إعدادات الجودة الأعلى فقدانًا أقل للبيانات وحجم ملف أكبر.</li>
        <li><strong>الإيجابيات:</strong> يمكن أن ينتج أحجام ملفات صغيرة جدًا للصور، مما يجعله مثاليًا للاستخدام على الويب. يدعم ملايين الألوان، مما يسمح بإنشاء صور غنية ومفصلة.</li>
        <li><strong>السلبيات:</strong> الضغط مع فقدان البيانات هو أكبر عيب فيه. في كل مرة تقوم فيها بإعادة حفظ ملف JPG، فإنه يخضع لجولة أخرى من الضغط، ويفقد المزيد من الجودة إلى الأبد. يسمى هذا "فقدان الجيل". الأهم من ذلك، **لا يدعم JPG الشفافية.** إذا قمت بحفظ شعار بخلفية شفافة بتنسيق JPG، فسيكون له خلفية بيضاء صلبة.</li>
    </ul>

    <h2>PNG: بطل الشفافية والرسومات</h2>
    <p>تم تطوير PNG، أو Portable Network Graphics، كبديل أقوى لتنسيق GIF الأقدم. ميزته القاتلة هي قدرته على التعامل مع الشفافية.</p>
    <ul>
        <li><strong>الأفضل لـ:</strong> الشعارات، والأيقونات، والرسوم التوضيحية، والصور التي تحتوي على نصوص كثيرة، وأي رسم يتطلب خلفية شفافة.</li>
        <li><strong>الضغط:</strong> يستخدم PNG ضغط "بدون فقدان البيانات". هذا يعني أنه يقلل حجم الملف دون التخلص من أي بيانات صورة. عندما تفتح ملف PNG وتعيد حفظه، لا تفقد أي جودة. الملف هو نسخة طبق الأصل من الأصل.</li>
        <li><strong>الإيجابيات:</strong> يدعم الشفافية الكاملة (alpha transparency)، مما يسمح بحواف ناعمة وشبه شفافة. يضمن الضغط بدون فقدان البيانات أن تظل رسوماتك ونصوصك حادة وواضحة تمامًا.</li>
        <li><strong>السلبيات:</strong> بالنسبة للصور الفوتوغرافية، تكون ملفات PNG أكبر بكثير من ملفات JPG، غالبًا ما تكون أكبر بخمسة إلى عشرة أضعاف. هذا يجعلها غير مناسبة للاستخدام العام للصور على الويب لأنها ستبطئ أوقات تحميل الصفحة بشكل كبير.</li>
    </ul>

    <h2>WEBP: المنافس الحديث للويب</h2>
    <p>تم تطوير WEBP بواسطة Google، وهو تنسيق صور من الجيل التالي مصمم خصيصًا لجعل الويب أسرع. إنه متعدد الاستخدامات، حيث يجمع أفضل ميزات كل من JPG و PNG.</p>
    <ul>
        <li><strong>الأفضل لـ:</strong> كل شيء تقريبًا على الويب. إنه بديل ممتاز لكل من JPG و PNG.</li>
        <li><strong>الضغط:</strong> WEBP متعدد الاستخدامات بشكل لا يصدق. يدعم كلاً من الضغط مع فقدان البيانات وبدون فقدان البيانات. في وضع فقدان البيانات، يمكن أن تكون ملفات WEBP أصغر بنسبة 25-35% من ملف JPG ذي الجودة المكافئة. في وضع عدم فقدان البيانات، يمكن أن تكون أصغر بنسبة 25-40% من ملف PNG.</li>
        <li><strong>الإيجابيات:</strong> الأفضل من العالمين. يوفر ضغطًا فائقًا لكل من JPG و PNG، مما يؤدي إلى مواقع ويب أسرع. كما أنه **يدعم الشفافية** تمامًا مثل PNG، حتى في وضع فقدان البيانات. يدعم حتى الرسوم المتحركة، مما يجعله بديلاً لملفات GIF أيضًا.</li>
        <li><strong>السلبيات:</strong> العيب الحقيقي الوحيد كان دعم المتصفح. ومع ذلك، اعتبارًا من عام 2025، أصبح WEBP مدعومًا الآن من قبل جميع المتصفحات الحديثة الرئيسية (Chrome، Firefox، Edge، Safari)، مما يجعله خيارًا آمنًا وموصى به للغاية لجميع محتوى الويب.</li>
    </ul>

    <h2>الحكم: شجرة قرار بسيطة</h2>
    <p>إليك كيفية اختيار التنسيق الصحيح في ثوانٍ:</p>
    <ol>
        <li><strong>هل تنشر على الويب؟</strong> إذا كانت الإجابة نعم، **استخدم WEBP**. إنه يوفر أفضل توازن بين الجودة وحجم الملف لكل موقف تقريبًا. استخدم ضغطه مع فقدان البيانات للصور وضغطه بدون فقدان البيانات للرسومات والشعارات الحادة.</li>
        <li><strong>هل تحتاج إلى شفافية ولا يمكنك استخدام WEBP؟</strong> إذا كنت بحاجة إلى خلفية شفافة لشعار أو أيقونة وتعمل في بيئة أقدم لا تدعم WEBP، **استخدم PNG**.</li>
        <li><strong>هل تحفظ صورة لنظام لا يدعم WEBP؟</strong> إذا كنت ترسل صورة في بريد إلكتروني أو تستخدم منصة قد لا تدعم WEBP، **استخدم JPG**. يظل التنسيق الأكثر توافقًا عالميًا للصور الفوتوغرافية.</li>
    </ol>

