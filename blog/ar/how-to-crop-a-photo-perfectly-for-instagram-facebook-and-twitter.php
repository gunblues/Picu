    <h2>ورقة الغش النهائية لقص وسائل التواصل الاجتماعي (2025)</h2>
    <p>يمكن أن تتغير متطلبات المنصة، ولكن هذه هي أهم نسب العرض إلى الارتفاع التي يجب معرفتها اليوم:</p>

    <h3>انستغرام:</h3>
    <ul>
        <li><strong>منشور مربع (1:1):</strong> المظهر الكلاسيكي لانستغرام. الحجم المثالي هو 1080 × 1080 بكسل. إنه خيار آمن ومتوازن يعمل بشكل جيد لمعظم الصور.</li>
        <li><strong>منشور عمودي (4:5):</strong> هذا هو الخيار الأفضل لزيادة مساحة الشاشة في الموجز المحمول. يشغل القص العمودي 4:5 مساحة أكبر من الشاشة مقارنة بالصورة المربعة أو الأفقية، مما يجذب المزيد من الانتباه. استهدف 1080 × 1350 بكسل.</li>
        <li><strong>منشور أفقي (1.91:1):</strong> على الرغم من أنه ممكن، إلا أن هذا هو عمومًا التنسيق الأقل فعالية لأنه ينشئ أصغر صورة في الموجز. استخدمه فقط عندما يكون التكوين الأفقي ضروريًا للغاية. استهدف 1080 × 566 بكسل.</li>
        <li><strong>القصص والبكرات (9:16):</strong> هذا هو تنسيق شاشة الهاتف العمودي القياسي. الحجم المثالي هو 1080 × 1920 بكسل. عند القص للقصص، تأكد من أن موضوعك الرئيسي في المنتصف، حيث يمكن أن تحجب واجهة المستخدم الجزء العلوي والسفلي.</li>
    </ul>

    <h3>فيسبوك:</h3>
    <ul>
        <li><strong>منشورات الموجز:</strong> فيسبوك أكثر مرونة من انستغرام. يعمل المربع 1:1 (1200 × 1200 بكسل) بشكل رائع. كما أن الصورة العمودية 4:5 (1200 × 1500 بكسل) فعالة جدًا.</li>
        <li><strong>صورة الغلاف (سطح المكتب):</strong> هذه صعبة بسبب شكلها العريض والبانورامي. الحجم الرسمي هو 820 × 312 بكسل، ولكنها تُعرض بشكل مختلف على الهاتف المحمول. من الأفضل الاحتفاظ بالمعلومات الأكثر أهمية (مثل النص أو الشعارات) في "منطقة آمنة" مركزية.</li>
        <li><strong>القصص (9:16):</strong> نفس قصص انستغرام، 1080 × 1920 بكسل.</li>
    </ul>

    <h3>تويتر (X):</h3>
    <ul>
        <li><strong>منشور صورة في الموجز:</strong> يفضل تويتر حاليًا نسبة عرض إلى ارتفاع **16:9** لمنشورات الصورة الواحدة في معاينة الجدول الزمني. استهدف 1600 × 900 بكسل. بينما يمكن للمستخدمين النقر لرؤية الصورة الكاملة، فإن تحسين نسبة العرض إلى الارتفاع هذه يضمن أن تبدو صورتك رائعة دون أي جهد إضافي من المشاهد. بالنسبة للمنشورات التي تحتوي على صور متعددة، قد يقوم تويتر بقصها إلى 1:1.</li>
        <li><strong>صورة الرأس:</strong> نسبة عرض إلى ارتفاع عريضة جدًا 3:1. الحجم الموصى به هو 1500 × 500 بكسل. على غرار أغلفة فيسبوك، حافظ على العناصر الرئيسية في المنتصف.</li>
    </ul>

