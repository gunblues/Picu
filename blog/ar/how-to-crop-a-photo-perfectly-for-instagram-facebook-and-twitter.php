    <h2>علم القص: نسب العرض إلى الارتفاع مشروحة</h2>
    <p>نسبة العرض إلى الارتفاع هي ببساطة العلاقة التناسبية بين عرض الصورة وارتفاعها. يتم كتابتها كصيغة: `العرض:الارتفاع`. تحتوي الصورة المربعة المثالية على نسبة عرض إلى ارتفاع 1:1، لأن عرضها وارتفاعها متساويان. يحتوي تلفزيون الشاشة العريضة القياسي على نسبة عرض إلى ارتفاع 16:9.</p>
