    <h2>فن القص: أكثر من مجرد تقليم</h2>
    <p>قبل أن ندخل في الأرقام الفنية، دعنا نتحدث عن *لماذا* نقص. يمكن للقص الجيد أن يحول الصورة عن طريق:</p>
    <ul>
        <li><strong>تحسين التكوين:</strong> يمكنك استخدام القص لتطبيق قواعد التكوين الكلاسيكية مثل قاعدة الأثلاث. تخيل شبكة 3x3 فوق صورتك؛ من خلال وضع العناصر الرئيسية على طول هذه الخطوط أو عند تقاطعاتها، يمكنك إنشاء صورة أكثر توازنًا وجاذبية بصرية.</li>
        <li><strong>إزالة المشتتات:</strong> هل توجد سلة مهملات مشتتة في زاوية صورتك؟ شخص غير معروف يمشي في الخلفية؟ القص هو أسهل طريقة للتخلص من هذه العناصر غير المرغوب فيها والحفاظ على التركيز حيث ينتمي.</li>
        <li><strong>تغيير السرد:</strong> يمكن أن تغير طريقة قصك للصورة قصتها. قد تظهر لقطة واسعة شخصًا في منظر طبيعي شاسع ووحيد، بينما يمكن أن يكشف قص ضيق على وجهه عن عاطفة معينة. يمنحك القص التحكم السردي.</li>
        <li><strong>التركيز على الموضوع:</strong> في بعض الأحيان يكون الجزء الأكثر أهمية في الصورة صغيرًا ضمن إطار أكبر. يسمح لك القص بالاقتراب من موضوعك، مما يجعله نقطة التركيز التي لا يمكن إنكارها في الصورة.</li>
