        <li><strong>لا تنسى التكوين:</strong> ضع في اعتبارك الصورة نفسها. إذا كانت إحدى الزوايا مظلمة جدًا والأخرى فاتحة جدًا، فاختر الزاوية التي ستكون فيها العلامة المائية أكثر وضوحًا ولكنها لا تزال دقيقة.</li>
