    <p>إذا كنت جديدًا في عالم تحرير الصور بخلاف الفلاتر وأشرطة التمرير البسيطة، فقد يبدو مفهوم "الطبقات" مخيفًا. إنه مصطلح تسمعه مرتبطًا ببرامج احترافية مثل Adobe Photoshop، وقد يبدو معقدًا. لكن الفكرة وراء الطبقات بسيطة بشكل لا يصدق، وبديهية، وقوية. يعد فهم الطبقات أهم خطوة يمكنك اتخاذها للانتقال من محرر أساسي إلى قوة إبداعية.</p>
    <p>فكر في الطبقات ككومة من الألواح الزجاجية الشفافة. يمكنك الرسم على كل لوح بشكل مستقل. يمكنك تغيير ترتيب الألواح، أو جعل اللوح أكثر أو أقل شفافية، أو حتى قطع ثقب في لوح واحد لرؤية اللوح الذي تحته. عندما تنظر إلى الأسفل عبر الكومة من الأعلى، سترى صورة واحدة مدمجة. هذا هو بالضبط كيف تعمل الطبقات في تحرير الصور.</p>

    <h2>لماذا تعد الطبقات تغييرًا جذريًا: التحرير غير المدمر</h2>
    <p>أهم ميزة لاستخدام الطبقات هي أنها تمكن من **التحرير غير المدمر**. دعنا نرى ما يعنيه ذلك.</p>
    <p>تخيل أنك ترسم على لوحة واحدة. ترسم سماء زرقاء جميلة، ثم ترسم جبلًا أمامها. ماذا لو قررت أنك تريد تحريك الجبل إلى اليسار؟ لا يمكنك ذلك. لقد تم دمج الجبل والسماء الآن في صورة واحدة؛ لقد اختفى الطلاء الأزرق الذي كان "خلف" الجبل إلى الأبد. هذا هو **التحرير المدمر**.</p>
    <p>الآن، تخيل استخدام ألواحنا الشفافة (الطبقات):</p>
    <ul>
        <li><strong>الطبقة 1 (الأسفل):</strong> ترسم السماء الزرقاء.</li>
        <li><strong>الطبقة 2 (الأعلى):</strong> ترسم الجبل.</li>
    </ul>
    <p>نظرًا لأن الجبل موجود على لوح منفصل، يمكنك الآن فعل أي شيء تريده به دون التأثير على السماء. يمكنك تحريكه، أو تغيير حجمه، أو تغيير لونه، أو حتى حذفه بالكامل، وستظل السماء الزرقاء في الطبقة السفلية سليمة تمامًا. هذا هو **التحرير غير المدمر**، ويمنحك مرونة كاملة للتجربة وتغيير رأيك في أي نقطة في العملية الإبداعية.</p>

    <h2>الاستخدامات الشائعة للطبقات: إطلاق العنان للإمكانيات الإبداعية</h2>
    <p>بمجرد فهمك للمفهوم، سترى أن الطبقات هي الأساس لجميع تقنيات التحرير المتقدمة تقريبًا.</p>
    
    <h3>1. دمج صور متعددة (التركيب)</h3>
    <p>هذا أحد الاستخدامات الأكثر شيوعًا. هل تريد استبدال سماء مملة في صورة بغروب شمس درامي من صورة أخرى؟ باستخدام الطبقات، الأمر سهل:</p>
    <ol>
        <li>افتح صورتك الرئيسية في الطبقة السفلية.</li>
        <li>أضف صورة غروب الشمس في طبقة فوقها.</li>
        <li>استخدم أداة (مثل مزيل الخلفية أو ممحاة) لإزالة السماء المملة من الطبقة السفلية، مما يكشف عن غروب الشمس الجميل من الطبقة السفلية.</li>
    </ol>

    <h3>2. إضافة نص ورسومات</h3>
    <p>عند إضافة نص أو شعار إلى صورة، يجب أن يكون دائمًا على طبقته المنفصلة. يتيح لك هذا ما يلي:</p>
    <ul>
        <li>تحريك النص في أي مكان دون إزعاج صورة الخلفية.</li>
        <li>تغيير الخط أو الحجم أو لون النص في أي وقت.</li>
        <li>إضافة تأثيرات مثل الظل المسقط أو المخطط التفصيلي إلى طبقة النص دون التأثير على الصورة الرئيسية.</li>
    </ul>

    <h3>3. إجراء التعديلات وتطبيق التأثيرات</h3>
    <p>نادرًا ما يطبق المحررون المحترفون التعديلات مباشرة على الصورة نفسها. بدلاً من ذلك، يستخدمون **طبقات التعديل**. طبقة التعديل هي نوع خاص من الطبقات لا تحتوي على بكسلات، بل تحتوي على تعليمات (مثل "زيادة التباين" أو "تغيير الألوان") وتطبقها على جميع الطبقات الموجودة أسفلها.</p>
    <p>الفائدة؟ إذا قررت أنك لا تحب التأثير، يمكنك ببساطة حذف طبقة التعديل، وستظل صورتك الأصلية كما هي. يمكنك أيضًا ضبط شفافيتها. على سبيل المثال، يمكنك إضافة طبقة تعديل بالأبيض والأسود، ثم خفض شفافيتها إلى 50% لإنشاء تأثير لوني باهت ورائع. لديك مرونة لا نهائية.</p>

    <h3>4. تنقيح الصور الشخصية</h3>
    <p>عند تنقيح صورة شخصية، فإن سير العمل الشائع هو إنشاء طبقة جديدة فارغة فوق الصورة. عندما تحتاج إلى إزالة عيب، يمكنك استخدام أداة الشفاء أو الاستنساخ لأخذ عينة من منطقة نظيفة من الجلد والرسم فوق العيب على *الطبقة الجديدة*. بهذه الطريقة، يتم الاحتفاظ بجميع تعديلاتك منفصلة عن الصورة الأصلية. إذا ارتكبت خطأ، فما عليك سوى مسح هذا الجزء من طبقة التنقيح، وليس صورتك الأصلية.</p>

    <h2>لوحة الطبقات الأساسية: ما تحتاج لمعرفته</h2>
    <p>في أي برنامج يدعم الطبقات، ستجد لوحة الطبقات. ستحتوي عادةً على بعض الميزات الرئيسية:</p>
    <ul>
        <li><strong>مكدس الطبقات:</strong> قائمة بجميع طبقاتك، مع الطبقة العلوية في أعلى القائمة. يمكنك سحب الطبقات لأعلى ولأسفل لتغيير ترتيبها.</li>
        <li><strong>إضافة طبقة جديدة:</strong> زر لإنشاء طبقة جديدة فارغة.</li>
        <li><strong>حذف الطبقة:</strong> زر لإزالة الطبقة المحددة.</li>
        <li><strong>الشفافية:</strong> شريط تمرير يتحكم في مدى شفافية الطبقة. 100% معتمة تمامًا، بينما 0% غير مرئية تمامًا.</li>
        <li><strong>الرؤية (أيقونة العين):</strong> يؤدي النقر على أيقونة العين بجانب الطبقة إلى إخفائها مؤقتًا، وهو أمر رائع لرؤية تأثير التعديل قبل وبعد.</li>
    </ul>

    <h2>الخاتمة</h2>
    <p>الطبقات هي حجر الزاوية في تحرير الصور الحديث والمرن والإبداعي. إنها تحررك من الخوف من ارتكاب أخطاء دائمة وتفتح عالمًا من الاحتمالات، من تراكبات النص البسيطة إلى التركيبات الفنية المعقدة. بينما قد لا تقدم أدوات الإنترنت البسيطة التعقيد الكامل لنظام طبقات Photoshop، فإن المفهوم الأساسي يظل كما هو. في المرة القادمة التي تريد فيها دمج صورتين أو إضافة نص إلى صورة، فكر في الطبقات. سيغير ذلك طريقة تحريرك بشكل أساسي.</p>
