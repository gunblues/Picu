    <h2>فهم المشكلة: ما هو التعريض؟</h2>
    <p>التعريض هو ببساطة الكمية الإجمالية للضوء المسموح لها بالوصول إلى مستشعر الكاميرا عند التقاط صورة.</p>
    <ul>
        <li><strong>التعريض الناقص:</strong> لم يصل ضوء كافٍ إلى المستشعر. والنتيجة هي صورة مظلمة مع فقدان التفاصيل في الظلال. سيكون الرسم البياني للصورة ذات التعريض الناقص متجمعًا في الجانب الأيسر.</li>
        <li><strong>التعريض الزائد:</strong> وصل ضوء كثير جدًا إلى المستشعر. والنتيجة هي صورة ساطعة بشكل مفرط مع فقدان التفاصيل في الإبرازات (الأجزاء الأكثر سطوعًا في الصورة). سيكون الرسم البياني للصورة ذات التعريض الزائد متجمعًا في الجانب الأيمن.</li>
    </ul>
    <p>هدفنا هو استخدام أدوات التحرير لإعادة توزيع معلومات الضوء هذه، وإنشاء صورة متوازنة تبدو طبيعية ومليئة بالتفاصيل.</p>

    <h2>مجموعة الأدوات الأساسية لإصلاح التعريض</h2>
    <p>لا تحتاج إلى عشرات الأدوات المعقدة. عدد قليل من أشرطة التمرير الرئيسية، الموجودة في كل محرر صور تقريبًا، ستنجز 99% من العمل.</p>

    <h3>1. للصور ذات التعريض الناقص (مظلمة جدًا)</h3>
    <p>عندما تكون صورتك مظلمة جدًا، يكون هدفك الأساسي هو إدخال المزيد من الضوء دون جعل الصورة تبدو مسطحة أو مشوشة.</p>
    <ol>
        <li><strong>ابدأ بشريط تمرير التعريض:</strong> هذا هو التحكم الرئيسي لديك. قم بزيادة التعريض بلطف لرفع السطوع العام للصورة حتى يصبح الموضوع الرئيسي مضاءً جيدًا.</li>
        <li><strong>رفع الظلال:</strong> بعد رفع التعريض، قد تبدو الأجزاء الأكثر قتامة من الصورة لا تزال موحلة. استخدم شريط تمرير **الظلال** لاستهداف هذه المناطق المظلمة وتفتيحها على وجه التحديد. هذه أداة رائعة للكشف عن التفاصيل المخفية في الظلال دون التأثير على أجزاء الصورة التي هي بالفعل ساطعة بما فيه الكفاية.</li>
        <li><strong>ضبط الأسود:</strong> يمكن أن يؤدي رفع الظلال أحيانًا إلى جعل النقطة الأكثر قتامة في صورتك تبدو رمادية حليبية بدلاً من الأسود الغني. لاستعادة نقطة سوداء عميقة وغنية، قم بتقليل شريط تمرير **الأسود** قليلاً. هذا يضيف تباينًا ويمنع الصورة من أن تبدو باهتة.</li>
        <li><strong>كن حذرًا من الضوضاء:</strong> يمكن أن يؤدي تفتيح صورة مظلمة جدًا بشكل كبير إلى إدخال "ضوضاء" رقمية أو حبيبات، والتي تبدو وكأنها بقع دقيقة. إذا حدث هذا، استخدم أداة تقليل الضوضاء لتنعيمها، ولكن طبقها باعتدال لتجنب مظهر بلاستيكي.</li>
    </ol>

    <h3>2. للصور ذات التعريض الزائد (ساطعة جدًا)</h3>
    <p>عندما تكون صورتك ساطعة جدًا، يكون هدفك هو استعادة التفاصيل المفقودة في الإبرازات دون جعل الصورة تبدو باهتة أو رمادية.</p>
    <ol>
        <li><strong>ابدأ بشريط تمرير التعريض:</strong> قم بتقليل التعريض بلطف لخفض السطوع العام وإعادة الصورة إلى نطاق طبيعي.</li>
        <li><strong>إنقاذ الإبرازات:</strong> هذه هي الخطوة الأكثر أهمية. غالبًا ما تحتوي الصورة ذات التعريض الزائد على إبرازات "محروقة"، حيث تكون المناطق الساطعة مثل السماء أو القميص الأبيض بيضاء نقية بدون نسيج. استخدم شريط تمرير **الإبرازات** لاستهداف هذه المناطق الساطعة وتغميقها على وجه التحديد. ستندهش غالبًا من مقدار التفاصيل (مثل اللون الأزرق للسماء أو نسيج فستان الزفاف) التي يمكنك استعادتها.</li>
        <li><strong>ضبط الأبيض:</strong> على غرار شريط تمرير الأسود، يحدد شريط تمرير **الأبيض** النقطة الأكثر سطوعًا في صورتك. بعد استعادة تفاصيل الإبرازات، قد تحتاج إلى زيادة شريط تمرير الأبيض قليلاً للتأكد من أن أجزاء الصورة التي *يجب* أن تكون ساطعة لا تزال تتمتع بمظهر نظيف وساطع.</li>
        <li><strong>إضافة لمسة من التباين:</strong> يمكن أن يؤدي خفض التعريض والإبرازات أحيانًا إلى جعل الصورة تبدو مسطحة بعض الشيء. يمكن أن يؤدي تعزيز صغير لشريط تمرير **التباين** في نهاية العملية إلى استعادة إحساس لطيف بالعمق.</li>
    </ol>

    <h2>قوة ملفات RAW</h2>
    <p>بينما يمكنك بالتأكيد إنقاذ ملف JPG، فإن ملف RAW يمنحك مرونة أكبر بكثير لهذه الأنواع من التصحيحات. ملف RAW هو ملف غير مضغوط يحتوي على جميع البيانات التي التقطها مستشعر الكاميرا. أما ملف JPG، فهو ملف مضغوط حيث اتخذت الكاميرا بالفعل قرارات وتخلصت من بعض تلك البيانات. هذا يعني أن ملف RAW يحتوي على تفاصيل مخفية أكثر بكثير في الظلال والإبرازات القصوى، مما يمنحك فرصة أفضل بكثير للتعافي الناجح.</p>

    <h2>ملخص سير عمل سريع</h2>
    <ul>
        <li><strong>مظلمة جدًا؟</strong> زيادة التعريض -> زيادة الظلال -> تقليل الأسود.</li>
        <li><strong>ساطعة جدًا؟</strong> تقليل التعريض -> تقليل الإبرازات -> زيادة الأبيض.</li>
    </ul>

