        <li><strong>الإبرازات:</strong> يستهدف شريط التمرير هذا على وجه التحديد الأجزاء الأكثر سطوعًا في صورتك. إذا كانت السماء في صورتك ساطعة جدًا وتبدو وكأنها كتلة بيضاء، فيمكنك سحب الإبرازات لأسفل لاستعادة اللون الأزرق وتفاصيل السحابة.</li>
        <li><strong>الظلال:</strong> هذا هو عكس الإبرازات. يستهدف على وجه التحديد الأجزاء الأكثر قتامة في صورتك. إذا كان وجه شخص ما مفقودًا في الظل، فيمكنك رفع شريط تمرير الظلال للكشف عن ملامحه دون جعل بقية الصورة ساطعة جدًا.</li>
