    <h3>1. توازن اللون الأبيض: ضبط درجة الحرارة الصحيحة</h3>
    <p>توازن اللون الأبيض هو أساس كل تصحيح للألوان. وظيفته هي إخبار الصورة كيف يجب أن يبدو "الأبيض الحقيقي". إذا كان توازن اللون الأبيض خاطئًا، فستحتوي صورتك بأكملها على تشوه لوني غير طبيعي. سترى عادةً شريطي تمرير رئيسيين:</p>
    <ul>
        <li><strong>درجة الحرارة:</strong> يضبط شريط التمرير هذا توازن الألوان بين الأزرق والأصفر. إذا تم التقاط صورتك في الداخل تحت ضوء التنجستن وبدت برتقالية جدًا، فستقوم بتحريك درجة الحرارة نحو الطرف الأزرق لتبريدها. إذا تم التقاطها في الظل وبدت زرقاء جدًا، فستقوم بتحريكها نحو الطرف الأصفر لتدفئتها.</li>
        <li><strong>الصبغة:</strong> يضبط شريط التمرير هذا التوازن بين الأخضر والأرجواني. يتم استخدامه بشكل أقل تكرارًا ولكنه ضروري لتصحيح التشوهات اللونية من أضواء الفلورسنت، والتي يمكن أن تعطي الصور غالبًا صبغة خضراء.</li>
    </ul>
    <p><strong>كيفية استخدامه:</strong> ابحث عن شيء في صورتك من المفترض أن يكون لونًا محايدًا (أبيض، رمادي، أو أسود). اضبط أشرطة تمرير درجة الحرارة والصبغة حتى يبدو هذا الكائن محايدًا حقًا، بدون أي تشوه لوني. بمجرد القيام بذلك، ستتخذ جميع الألوان الأخرى في الصورة مكانها بشكل طبيعي.</p>

