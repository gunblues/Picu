    <p>الرسم البياني هو تمثيل رسومي للنطاق اللوني لصورك. يخبرك بالقصة الدقيقة للبكسلات الفاتحة والداكنة في صورتك، خالية من التفسير الذاتي لعينيك أو السطوع المتغير لشاشتك. إنه سلاحك السري لتحقيق تعريض مثالي تقنيًا في كل مرة.</p>

    <h2>ما هو الرسم البياني، بالضبط؟</h2>
    <p>تخيل أن لديك مخططًا شريطيًا يحتوي على 256 شريطًا رأسيًا. يمثل كل شريط مستوى سطوع محددًا، من 0 (أسود نقي) في أقصى اليسار إلى 255 (أبيض نقي) في أقصى اليمين. يمثل منتصف المخطط الدرجات اللونية المتوسطة (الرمادي المتوسط).</p>
    <p>الآن، يمر الرسم البياني عبر كل بكسل في صورتك ويقرر مدى سطوعه. إذا كان البكسل أسود نقيًا، فإنه يضيف عدًا واحدًا إلى الشريط في الموضع 0. إذا كان البكسل أبيض نقيًا، فإنه يضيف عدًا واحدًا إلى الشريط في الموضع 255. إذا كان البكسل رماديًا متوسطًا، فإنه يضيف عدًا إلى شريط في المنتصف.</p>
    <p>يُظهر لك الرسم البياني النهائي توزيع البكسلات عبر جميع مستويات السطوع. يخبرك ارتفاع الرسم البياني في أي نقطة بعدد البكسلات في صورتك التي لها هذا السطوع المحدد. باختصار، الرسم البياني هو تعداد للدرجات اللونية في صورتك.</p>

    <h2>كيفية قراءة خريطة الرسم البياني</h2>
    <p>المحور الأفقي هو الجزء الأكثر أهمية. وهو مقسم إلى ثلاث مناطق رئيسية:</p>
    <ul>
        <li><strong>الجانب الأيسر (الظلال):</strong> تمثل هذه المنطقة البكسلات الداكنة في صورتك. إذا كان لديك ارتفاع كبير في البيانات مدفوعًا نحو الحافة اليسرى القصوى، فهذا يعني أن لديك مناطق سوداء نقية في صورتك.</li>
        <li><strong>المنتصف (الدرجات اللونية المتوسطة):</strong> هذا هو المكان الذي توجد فيه غالبية المعلومات اللونية في الصورة المتوازنة جيدًا عادةً. يمثل هذا الرمادي والنطاقات المتوسطة من الألوان.</li>
        <li><strong>الجانب الأيمن (الإبرازات):</strong> تمثل هذه المنطقة البكسلات الساطعة. إذا كان لديك ارتفاع كبير في البيانات مدفوعًا نحو الحافة اليمنى القصوى، فهذا يعني أن لديك مناطق بيضاء نقية.</li>
    </ul>

    <h2>مخاطر "المنحدرات": شرح القص</h2>
    <p>المعلومة الأكثر أهمية التي يوفرها الرسم البياني هي ما إذا كان لديك **قص**. يحدث القص عندما تتجمع الرسم البياني على الحواف الصلبة على اليسار أو اليمين.</p>
    <ul>
        <li><strong>قص الظلال (الأسود المسحوق):</strong> إذا كان الرسم البياني يحتوي على ارتفاع حاد أو "منحدر" عند الموضع 0 (أقصى اليسار)، فهذا يعني أنه تم تسجيل عدد كبير من البكسلات على أنها سوداء نقية. يتم فقدان جميع التفاصيل في تلك المناطق ولا يمكن استعادتها. لقد "سحقت الأسود".</li>
        <li><strong>قص الإبرازات (الأبيض المحروق):</strong> إذا كان الرسم البياني يحتوي على منحدر عند الموضع 255 (أقصى اليمين)، فهذا يعني أن لديك بكسلات بيضاء نقية. هذا شائع في السماء الساطعة أو الانعكاسات. لقد اختفت جميع التفاصيل في هذه المناطق إلى الأبد. لقد "حرقت الإبرازات".</li>
    </ul>
    <p><strong>الهدف الأول للتعريض الجيد هو التقاط أكبر قدر ممكن من البيانات دون قص كبير في أي من الطرفين.</strong></p>

    <h2>لا يوجد شيء اسمه شكل رسم بياني "مثالي"</h2>
    <p>هذا مفهوم خاطئ شائع. لا يوجد شكل مثالي واحد للرسم البياني. الشكل هو ببساطة انعكاس للمشهد الذي صورته.</p>
    <ul>
        <li><strong>صورة داكنة، ذات إضاءة منخفضة:</strong> صورة قطة سوداء في غرفة مظلمة سيكون لها بشكل طبيعي رسم بياني مع معظم بياناتها متجمعة في الجانب الأيسر. هذا أمر جيد تمامًا ويمثل المشهد بدقة.</li>
        <li><strong>صورة ساطعة، ذات إضاءة عالية:</strong> صورة دب قطبي في عاصفة ثلجية سيكون لها رسم بياني مع معظم بياناتها مدفوعة إلى اليمين. هذا صحيح أيضًا.</li>
        <li><strong>صورة "متوازنة":</strong> صورة منظر طبيعي نموذجية مع مزيج جيد من الظلال، والدرجات اللونية المتوسطة، والإبرازات قد يكون لها شكل يشبه الجبل اللطيف في المنتصف.</li>
    </ul>
    <p>الشكل نفسه لا يهم. ما يهم هو تجنب المنحدرات. لا تريد أن يتم قص رسم بياني لمشهد مظلم على اليمين، ولا تريد أن يتم قص رسم بياني لمشهد ساطع على اليسار.</p>

    <h2>استخدام الرسم البياني أثناء التحرير</h2>
    <p>عندما تفتح صورتك في محرر، اجعل الرسم البياني مرئيًا. سيكون دليلك الموضوعي.</p>
    <ol>
        <li><strong>التحقق من القص الأولي:</strong> انظر إلى الرسم البياني قبل أن تفعل أي شيء. هل هناك ارتفاعات في أي من الطرفين؟ هذا يخبرك ما إذا كانت صورتك الأصلية قد فقدت أي بيانات.</li>
        <li><strong>شاهد أثناء التعديل:</strong> بينما تحرك أشرطة تمرير التعريض، والتباين، والإبرازات، والظلال، شاهد كيف يتغير الرسم البياني في الوقت الفعلي.</li>
        <li><strong>استخدام أشرطة التمرير:</strong>
            <ul>
                <li>إذا رأيت قصًا للإبرازات على اليمين، اسحب شريط تمرير **الإبرازات** أو **التعريض** لأسفل وشاهد هذا الارتفاع في الجانب الأيمن يتحرك للداخل، بعيدًا عن الحافة.</li>
                <li>إذا رأيت قصًا للظلال على اليسار، ادفع شريط تمرير **الظلال** أو **الأسود** لأعلى وشاهد الجانب الأيسر من الرسم البياني يتحرك إلى اليمين، مستعيدًا تلك التفاصيل.</li>
            </ul>
        </li>
    </ol>

    <h2>الخاتمة</h2>
    <p>توقف عن الاعتماد على عينيك فقط. قد يكون سطوع شاشتك مضللاً، وقد يتغير إدراكك للصورة اعتمادًا على الإضاءة المحيطة في غرفتك. الرسم البياني هو مصدر الحقيقة الخاص بك. إنه أداة موضوعية تعتمد على البيانات تخبرك بالقصة الحقيقية لتعريض صورتك. يتطلب تعلم قراءتها القليل من الممارسة، ولكنه أسرع طريقة لاكتساب الثقة في تحريرك ولضمان أنك تحافظ على كل جزء ثمين من التفاصيل في صورك. اجعل الرسم البياني أفضل صديق لك، ولن تكون في الظلام بشأن تعريضك مرة أخرى أبدًا.</p>
