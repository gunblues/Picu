    <h2>裁切的藝術：不僅僅是修剪</h2>
    <p>在我們進入技術數據之前，讓我們先談談*為什麼*要裁切。好的裁切可以透過以下方式改變一張照片：</p>
    <ul>
        <li><strong>改善構圖：</strong>您可以使用裁切來應用像三分法這樣的經典構圖規則。想像一下在您的照片上覆蓋一個 3x3 的網格；透過將關鍵元素放置在這些線上或它們的交點上，您可以創造出一個更平衡、更具視覺吸引力的影像。</li>
        <li><strong>移除干擾物：</strong>您照片的角落裡有一個分散注意力的垃圾桶嗎？背景中有一個不知名的人在走動嗎？裁切是消除這些不必要元素並將焦點保持在應有位置的最簡單方法。</li>
        <li><strong>改變敘事：</strong>您裁切照片的方式可以改變它的故事。一張寬景照片可能顯示一個人在廣闊、孤獨的風景中，而對他們臉部的緊密裁切則可以揭示一種特定的情感。裁切賦予您敘事控制權。</li>
        <li><strong>聚焦主體：</strong>有時一張照片最重要的部分在一個較大的畫框中顯得很小。裁切讓您能更接近您的主體，使其成為影像不容置疑的焦點。</li>
    </ul>

    <h2>裁切的科學：長寬比解釋</h2>
    <p>長寬比就是圖片寬度與高度的比例關係。它以公式 `寬度:高度` 的形式書寫。一張完美的正方形圖片的長寬比為 1:1，因為它的寬度和高度相等。一台標準的寬螢幕電視的長寬比為 16:9。</p>
    <p>使用像 Picu 的線上裁切工具，您可以選擇一個特定的長寬比。這會限制裁切框，所以您可以自由移動和調整它的大小，同時確信最終的形狀將完美適合您選擇的平台。</p>

    <h2>終極社群媒體裁切速查表 (2025)</h2>
    <p>平台要求可能會改變，但這些是今天需要知道的最重要的長寬比：</p>

    <h3>Instagram：</h3>
    <ul>
        <li><strong>正方形貼文 (1:1)：</strong>經典的 Instagram 外觀。理想尺寸為 1080 x 1080 像素。這是一個安全、平衡的選擇，適用於大多數圖片。</li>
        <li><strong>直向貼文 (4:5)：</strong>這是在行動動態中最大化您螢幕空間的最佳選擇。一個垂直的 4:5 裁切比正方形或橫向照片佔據更多的螢幕，更能吸引注意力。目標尺寸為 1080 x 1350 像素。</li>
        <li><strong>橫向貼文 (1.91:1)：</strong>雖然可行，但這通常是最低效的格式，因為它在動態中產生的圖片最小。僅在水平構圖絕對必要時使用。目標尺寸為 1080 x 566 像素。</li>
        <li><strong>限時動態與 Reels (9:16)：</strong>這是標準的垂直手機螢幕格式。理想尺寸為 1080 x 1920 像素。為限時動態裁切時，請確保您的主要主體居中，因為最頂部和最底部可能會被使用者介面遮擋。</li>
    </ul>

    <h3>Facebook：</h3>
    <ul>
        <li><strong>動態貼文：</strong>Facebook 比 Instagram 更靈活。1:1 的正方形 (1200 x 1200 像素) 效果很好。4:5 的直向 (1200 x 1500 像素) 也非常有效。</li>
        <li><strong>封面照片（桌面版）：</strong>由於其寬闊的全景形狀，這是一個棘手的問題。官方尺寸為 820 x 312 像素，但在行動裝置上的顯示方式不同。最好將最關鍵的資訊（如文字或標誌）放在中央的「安全區」。</li>
        <li><strong>限時動態 (9:16)：</strong>與 Instagram 限時動態相同，1080 x 1920 像素。</li>
    </ul>

    <h3>Twitter (X)：</h3>
    <ul>
        <li><strong>動態內圖片貼文：</strong>Twitter 目前偏好在時間軸預覽中為單張圖片貼文使用 **16:9** 的長寬比。目標尺寸為 1600 x 900 像素。雖然使用者可以點擊查看完整圖片，但為此預覽長寬比進行優化可確保您的照片看起來很棒，而無需觀眾付出額外努力。對於有多張圖片的貼文，Twitter 可能會將它們裁切為 1:1。</li>
        <li><strong>頁首照片：</strong>一個非常寬的 3:1 長寬比。建議尺寸為 1500 x 500 像素。與 Facebook 封面類似，將關鍵元素保持在中央。</li>
    </ul>

    <h2>一個簡單的裁切工作流程</h2>
