        <li><strong>構圖您的畫面：</strong>移動和調整裁切框的大小。注意三分法。確保您沒有笨拙地切掉四肢或重要細節。</li>
        <li><strong>裁切並儲存：</strong>應用裁切並儲存您新的、格式完美的圖片。</li>
    </ol>

