    <p>在攝影中，很少有什麼事比拍下自以為完美的瞬間，事後卻發現影像柔焦、輕微失焦或模糊更令人失望了。照片模糊的原因有很多：相機晃動、主體移動、對焦點失誤，甚至是縮小圖片後出現的自然柔化。雖然您無法神奇地修復一張完全失焦的相片，但絕對可以拯救並顯著改善僅是稍微柔焦的照片。</p>
    <p>本指南將為您提供五個實用、易於執行的技巧，來銳化您的影像，並帶回您所期望的清晰細節。這些技術可以使用大多數相片編輯軟體來應用，包括像 Picu 這樣強大的線上工具。</p>

    <h2>首先，了解模糊的類型</h2>
    <p>並非所有模糊都是一樣的。找出原因可以幫助您設定切合實際的期望：</p>
    <ul>
        <li><strong>動態模糊：</strong>當相機或主體在曝光期間移動時發生，會導致條紋或鬼影。這是最難完全修復的類型。</li>
        <li><strong>失焦模糊：</strong>當相機鏡頭對焦在錯誤的點上時發生（例如，背景而非人物）。</li>
        <li><strong>一般柔焦：</strong>這是一種輕微的清晰度不足，可能是由品質較低的鏡頭、大氣霧霾或縮小影像的副作用所引起。<strong>這是最容易修復的模糊類型。</strong></li>
    </ul>
    <p>我們銳化的目標是透過增強照片中邊緣的對比度來提高*感知*的清晰度。它不會創造新的細節，但可以使現有細節更加明顯。</p>

    <h2>技巧 1：標準銳化濾鏡（請謹慎使用）</h2>
    <p>最常見的工具是簡單的「銳化」滑桿。這是一個比較粗糙的工具，但如果非常小心地使用，效果會很好。</p>
    <p><strong>運作原理：</strong>標準銳化濾鏡會增加它找到的任何邊緣上明暗像素之間的對比度。<br>
    <strong>如何使用：</strong>以非常小的增量應用銳化。放大到 100% 以準確判斷效果。目標是讓邊緣看起來清晰，而不是在邊緣周圍產生明亮的發光光暈。如果您看到光暈，那就表示您做得太過了。因此，許多編輯者更喜歡使用更進階的方法。</p>

    <h2>技巧 2：「Unsharp Mask (遮色片銳利化)」以獲得更多控制</h2>
    <p>儘管名稱令人困惑，Unsharp Mask (USM) 是一個更精密、更強大的銳化工具。它提供三個滑桿進行精確控制：</p>
    <ul>
        <li><strong>總量（或強度）：</strong>控制銳化的強度。它決定邊緣像素變得多暗或多亮。（例如，50-150%）。</li>
        <li><strong>半徑：</strong>決定將受影響的邊緣周圍區域的大小。對於細節豐富的照片，較小的半徑（0.5-2 像素）是最佳選擇，因為它能將銳化效果限制在邊緣。較大的半徑會產生更粗、更明顯的邊緣。</li>
        <li><strong>臨界值：</strong>此滑桿告訴工具忽略影像中沒有強烈邊緣的區域。增加臨界值可以保護平滑的區域，如皮膚或晴朗的天空，使其免於被銳化，從而防止工具放大不必要的雜訊或顆粒。2-10 的臨界值是一個很好的起點。</li>
    </ul>
    <p><strong>工作流程：</strong>從低的總量、約 1 像素的半徑和 3 的臨界值開始。逐漸增加總量，直到您看到清晰度有顯著改善，且沒有產生光暈。</p>

    <h2>技巧 3：增加紋理或清晰度</h2>
    <p>許多現代相片編輯器都有名為「紋理」或「清晰度」的滑桿，它們提供了更智慧的方式來增強細節。</p>
    <ul>
        <li><strong>清晰度：</strong>這會增強影像的中間色調。它非常適合讓事物看起來更具戲劇性和粗獷感，但如果過度使用在人像上可能會很刺眼。</li>
        <li><strong>紋理：</strong>這是一個更精細的工具，針對非常精細的細節。它非常適合帶出織物、樹葉或建築的紋理，而不會影響影像的較大區域。對於細微的銳化，它通常是比清晰度更好的選擇。</li>
    </ul>
    <p>首先輕推紋理滑桿，看看它如何帶出您影像中的精細圖案。這是在不冒傳統銳化產生光暈風險的情況下增加清晰度的好方法。</p>

    <h2>技巧 4：高反差保留（進階技巧）</h2>
    <p>這是專業攝影師最喜歡的技巧之一，常用於 Photoshop 等軟體。它涉及建立影像的重複圖層，對其應用「高反差保留」濾鏡（這會分離出邊緣），然後使用覆蓋或柔光混合模式將該圖層與原始圖層混合。雖然對大多數線上工具來說太複雜，但值得了解，因為它提供了最乾淨、最可控的銳化效果。</p>

    <h2>技巧 5：選擇性銳化</h2>
    <p>並非影像的每個部分都需要銳利。在人像中，您希望眼睛非常銳利，但可能希望皮膚保持柔和。如果您的工具允許，請使用筆刷或遮色片選擇性地應用銳化。銳化重要的細節——眼睛、建築物的細節、花朵的紋理——並保持其他區域不變。這種技術模仿了我們的眼睛自然感知場景的方式，從而產生更專業、更令人愉悅的影像。</p>

    <h2>結論</h2>
    <p>雖然您無法修復一張完全毀損的照片，但您擁有一套強大的工具來對抗柔焦和模糊。關鍵是要做到細微和精確。無論您是使用簡單的銳化滑桿、可控的 Unsharp Mask，還是智慧的紋理滑桿，目標始終相同：增強邊緣並帶回細節，而不引入不必要的失真。透過應用這些技巧，您可以拯救許多輕微模糊的照片，並確保您的最終影像盡可能清晰。</p>

