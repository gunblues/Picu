    <h2>了解問題：什麼是曝光？</h2>
    <p>曝光簡而言之就是您拍照時允許到達相機感光元件的總光量。</p>
    <ul>
        <li><strong>曝光不足：</strong>到達感光元件的光線不足。結果是一張黑暗的影像，陰影部分細節盡失。曝光不足照片的直方圖會集中在左側。</li>
        <li><strong>過度曝光：</strong>到達感光元件的光線過多。結果是一張過於明亮的影像，亮部（影像最亮的部分）細節盡失。過度曝光照片的直方圖會集中在右側。</li>
    </ul>
    <p>我們的目標是使用編輯工具重新分配這些光線資訊，創造出一張看起來自然且充滿細節的平衡影像。</p>

    <h2>修復曝光的基本工具組</h2>
    <p>您不需要數十種複雜的工具。幾個關鍵的滑桿，幾乎在每個照片編輯器中都能找到，將完成 99% 的工作。</p>

    <h3>1. 對於曝光不足的照片（太暗）</h3>
    <p>當您的照片太暗時，您的主要目標是在不使影像看起來平淡或充滿雜訊的情況下引入更多光線。</p>
    <ol>
        <li><strong>從曝光滑桿開始：</strong>這是您的主控制項。輕輕增加曝光度，以提高影像的整體亮度，直到主要主體光線充足。</li>
        <li><strong>拉高陰影：</strong>在您提高曝光後，影像最暗的部分可能仍然看起來混濁。使用<strong>陰影</strong>滑桿專門針對並提亮這些黑暗區域。這是一個絕佳的工具，可以在不影響影像中已經足夠明亮部分的情況下，揭示隱藏在陰影中的細節。</li>
        <li><strong>調整黑色色階：</strong>拉高陰影有時會使您影像中最暗的點看起來像乳灰色。要恢復深邃、濃郁的黑點，請稍微降低<strong>黑色色階</strong>滑桿。這會增加對比度，防止影像看起來褪色。</li>
        <li><strong>注意雜訊：</strong>大幅提亮一張非常暗的照片可能會引入數位「雜訊」或顆粒，看起來像細小的斑點。如果發生這種情況，請使用降噪工具將其平滑，但要謹慎使用，以避免塑膠感。</li>
    </ol>

    <h3>2. 對於過度曝光的照片（太亮）</h3>
    <p>當您的照片太亮時，您的目標是在不使影像看起來暗淡或灰濛濛的情況下，恢復失去的亮部細節。</p>
    <ol>
        <li><strong>從曝光滑桿開始：</strong>輕輕降低曝光度，以降低整體亮度，使影像回到正常範圍。</li>
        <li><strong>拯救亮部：</strong>這是最關鍵的步驟。過度曝光的照片通常有「過曝」的亮部，其中像天空或白襯衫等明亮區域是純白色，沒有任何紋理。使用<strong>亮部</strong>滑桿專門針對並調暗這些明亮區域。您通常會驚訝地發現可以恢復多少細節（如天空的藍色或婚紗的紋理）。</li>
        <li><strong>調整白色色階：</strong>與黑色色階滑桿類似，<strong>白色色階</strong>滑桿設定您影像中最亮的點。在您恢復了亮部細節後，您可能需要稍微增加白色色階滑桿，以確保影像中*應該*明亮的部分仍然有乾淨、明亮的感覺。</li>
        <li><strong>加回一點對比度：</strong>降低曝光和亮部有時會使影像看起來有點平。在過程結束時對<strong>對比度</strong>滑桿進行小幅提升，可以恢復良好的深度感。</li>
    </ol>

    <h2>RAW 檔案的力量</h2>
    <p>雖然您當然可以拯救 JPG，但 RAW 檔案為您提供了更大的修正空間。RAW 檔案是一種未壓縮的檔案，包含相機感光元件捕捉到的所有數據。而 JPG 則是一種壓縮檔案，相機已經做出了決定並丟棄了部分數據。這意味著 RAW 檔案在極端陰影和亮部中保留了更多的隱藏細節，讓您有更大的成功恢復機會。</p>

    <h2>快速工作流程摘要</h2>
    <ul>
        <li><strong>太暗？</strong>增加曝光 -> 增加陰影 -> 降低黑色色階。</li>
        <li><strong>太亮？</strong>降低曝光 -> 降低亮部 -> 增加白色色階。</li>
    </ul>

