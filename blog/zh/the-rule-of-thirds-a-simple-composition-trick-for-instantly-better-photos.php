    <h2>請記住：這是一個指導原則，而不是法律</h2>
    <p>像所有藝術「規則」一樣，三分法旨在作為一個指導原則，而不是一個永遠不能打破的僵硬法律。有時，一個完美置中的主體對於特定照片來說是最有效的選擇，特別是為了創造對稱感、穩定感和直接感。但是，您應該先學習並練習這個規則。一旦您了解了它*為什麼*有效，您也就會明白何時為了創意效果而打破它。</p>

