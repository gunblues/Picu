    <h2>什麼是三分法？</h2>
    <p>三分法非常簡單。想像您的影像被兩條垂直線和兩條水平線分成九個相等的部分，就像一個井字遊戲板。這個規則建議您應該將場景中最重要的元素放置在這些線上，或它們相交的點上。這些交點通常被稱為「力量點」。</p>
    <p>大多數現代相機和智慧型手機應用程式都有一個選項，可以在螢幕上顯示 3x3 的網格疊加層，這使得在拍攝時練習這個規則變得非常容易。</p>

    <h2>為什麼它有效？規則背後的心理學</h2>
    <p>初學者的自然傾向是將他們的主體直接放置在畫面的中心。雖然這有時可以有效地創造對稱感和穩定感，但它通常會導致照片感覺靜態、無聊和可預測。</p>
    <p>根據三分法，將您的主體偏離中心放置，可以創造出更具動態和視覺趣味的構圖。原因如下：</p>
    <ul>
        <li><strong>它創造了平衡和張力：</strong>透過將您的主體放置在畫面的一側，您在另一側創造了一種「負空間」感。主體和負空間之間的這種相互作用創造了一種視覺張力和平衡，對觀者來說更具吸引力。</li>
        <li><strong>它鼓勵眼睛移動：</strong>當主體偏離中心時，觀者的眼睛會自然地被鼓勵在畫面中移動，探索整個場景。置中的主體有時會讓眼睛停滯不前。</li>
        <li><strong>它創造了更自然的感覺：</strong>這個規則有助於創造感覺更自然、更不刻意的構圖。它允許主體存在於其環境中，而不是一個靜態的靶心。</li>
    </ul>

    <h2>如何在實踐中應用三分法</h2>
    <p>讓我們看看如何將網格用於不同類型的攝影。</p>

    <h3>對於風景：</h3>
    <ul>
        <li>不要將地平線直接放置在照片的中央，而是將其放置在頂部或底部水平線上。</li>
        <li><strong>您應該選擇哪條線？</strong>這取決於什麼更有趣。如果您有一個戲劇性、美麗的天空，請將地平線放置在底線上，將三分之二的畫面留給天空。如果前景更有趣（例如一片花田或有紋理的海灘），請將地平線放置在頂線上以強調陸地。</li>
    </ul>

    <h3>對於人像：</h3>
    <ul>
        <li>將您的主體放置在左側或右側垂直線上。</li>
        <li>將他們最重要的特徵——通常是他們的眼睛——放置在其中一個頂部交點上。這會創造一個強大的焦點。</li>
        <li>讓主體看向或移動到負空間中。例如，如果人物在左側垂直線上，他們應該看向畫面的右側。這會創造一種期待感，並給主體「呼吸空間」。</li>
    </ul>

    <h3>對於移動的主體：</h3>
    <ul>
        <li>如果您正在拍攝一個移動的物體，例如汽車或跑步者，請將他們放置在其中一條垂直線上，並在他們移動的方向上留下空白空間。這讓觀者對主體的去向有所了解，並創造一種運動感。</li>
    </ul>

