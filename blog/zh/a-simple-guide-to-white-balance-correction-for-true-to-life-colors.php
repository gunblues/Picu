    <p>您是否曾經在室內拍照，結果照片看起來異常橘黃？或是在陰影下拍照，照片卻呈現不自然的藍色調？這個常見問題是白平衡不正確所導致的。我們的大腦非常厲害，能自動適應不同類型的光線，所以無論是在溫暖的燈光下，或是在陰天涼爽的光線下，我們都能將一張白紙感知為白色。然而，數位相機就沒那麼聰明了。它們只會如實記錄光線，這往往會導致不必要的色偏。</p>
    <p>白平衡校正是移除這些不真實色偏的過程，讓在現實中看起來是白色的物體，在您的照片中也能呈現為白色。這是色彩校正的絕對基礎。如果您的白平衡錯誤，照片中的所有其他顏色也都會跟著出錯。掌握這個簡單的調整，是讓您的影像色彩自然、準確且美麗的第一步，也是最重要的一步。</p>

    <h2>了解色溫</h2>
    <p>白平衡背後的核心概念是<strong>色溫</strong>。不同的光源會產生不同顏色的光。這種顏色是以一個稱為克耳文（K）的溫標來衡量的。</p>
    <ul>
        <li><strong>暖光（較低的克耳文值）：</strong>燭光或傳統鎢絲燈泡會產生非常溫暖的橘黃色光。這在溫標的低端（約 1000-3000K）。</li>
        <li><strong>中性光（正午陽光）：</strong>正午時分的直射陽光被認為是相對中性或「白色」的光（約 5500K）。</li>
        <li><strong>冷光（較高的克耳文值）：</strong>在陰天或陰影下的光線實際上是帶藍色調的，也就是冷色調。這在溫標的高端（約 6500-10,000K）。</li>
    </ul>
    <p>白平衡設定的工作就是補償光源的色溫，以產生一張中性的影像。如果您在暖光下拍攝，相機需要增加藍色來中和橘色。如果您在冷光下拍攝，相機需要增加黃色/橘色來中和藍色。</p>

    <h2>白平衡校正工具</h2>
    <p>在您的相片編輯器中，您通常會找到三種主要的白平衡調整工具。</p>

    <h3>1. 白平衡預設集</h3>
    <p>大多數編輯器都提供一個預設集的下拉式選單，這些預設集與您在相機中可能找到的設定相符。這些選項包括「日光」、「陰天」、「陰影」、「鎢絲燈」和「螢光燈」。如果您知道照片是在哪種光線條件下拍攝的，選擇相應的預設集通常能讓您立即得到非常接近正確的結果。例如，如果您的室內照片看起來偏橘，選擇「鎢絲燈」預設集會自動增加藍色來抵銷它。</p>

    <h3>2. 色溫與色調滑桿</h3>
    <p>這些滑桿讓您能手動控制，進行細微的色彩微調。</p>
    <ul>
        <li><strong>色溫：</strong>這是主要的滑桿。它沿著藍色到黃色的軸線調整顏色。如果您的影像太藍，就將滑桿往黃色方向移動，使其變暖。如果您的影像太橘，就將滑桿往藍色方向移動，使其變冷。</li>
        <li><strong>色調：</strong>這個滑桿沿著綠色到洋紅色的軸線調整顏色。這用於校正更不尋常的光源，最顯著的是螢光燈，它通常會產生綠色的色偏。如果您校正了色溫，但照片看起來還是有點「不對勁」，對色調滑桿做個小小的調整通常就能解決問題。</li>
    </ul>

    <h3>3. 白平衡選擇器（滴管工具）</h3>
    <p>這通常是設定白平衡最快且最準確的方法。滴管工具讓您能告訴軟體什麼應該是中性色。</p>
    <ol>
        <li><strong>選擇工具：</strong>在您的白平衡面板中找到並選擇滴管圖示。</li>
        <li><strong>找到一個中性點：</strong>在您的照片中尋找一個您確定應該是中性色的物體——白色、中灰色或黑色都可以。好的選擇包括白襯衫、灰色人行道、某人眼中的眼白或價格標籤。</li>
        <li><strong>點擊中性點：</strong>用滴管點擊那個中性點。軟體會自動分析您點擊的像素顏色，並立即調整色溫和色調滑桿，使這些像素變得完全中性。</li>
    </ol>
    <p>因為軟體現在知道什麼是「真正的中性色」，它就能準確地重新對應影像中的所有其他顏色，一次點擊就移除整張照片的色偏。這是一個功能強大且效率極高的工具。</p>

    <h2>簡易白平衡工作流程</h2>
    <ol>
        <li><strong>先試試滴管工具：</strong>掃描您的影像，找一個中性點。如果能找到，滴管工具是您獲得準確結果的最快途徑。</li>
        <li><strong>如果沒有中性點，就使用預設集：</strong>如果您的照片沒有明顯的中性色（例如，日落或森林場景），請根據您記得的光線條件嘗試套用預設集。</li>
        <li><strong>用滑桿進行微調：</strong>使用滴管或預設集後，根據您自己的創意判斷，使用色溫和色調滑桿進行小的最終調整。您可能會想讓場景感覺稍微溫暖或涼爽一些，以達到創意效果。</li>
    </ol>

