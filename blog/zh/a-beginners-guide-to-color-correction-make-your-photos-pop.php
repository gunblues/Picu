    <h2>色彩的基石：關鍵調整</h2>
    <p>您不需要成為色彩科學家才能校正您的照片。您只需要了解幾乎所有照片編輯應用程式（包括像 Picu 這樣的線上工具）中都存在的幾個基本滑桿。</p>
    
    <h3>1. 白平衡：設定正確的色溫</h3>
    <p>白平衡是所有色彩校正的基礎。它的作用是告訴照片什麼應該是「真正的白色」。如果白平衡不對，您的整張照片都會有不自然的色偏。您通常會看到兩個主要滑桿：</p>
    <ul>
        <li><strong>色溫：</strong>此滑桿調整藍色和黃色之間的色彩平衡。如果您的照片是在鎢絲燈下拍攝且看起來太橘，您會將色溫滑向藍色端以降溫。如果是在陰影下拍攝且看起來太藍，您會將其滑向黃色端以升溫。</li>
        <li><strong>色調：</strong>此滑桿調整綠色和洋紅色之間的平衡。它較少使用，但對於校正螢光燈造成的色偏至關重要，螢光燈通常會給照片帶來綠色的色調。</li>
    </ul>
    <p><strong>如何使用：</strong>在您的照片中找到一個應該是中性色的物體（白色、灰色或黑色）。調整色溫和色調滑桿，直到該物體看起來真正中性，沒有任何色偏。一旦您這樣做，照片中的所有其他顏色通常都會歸位。</p>

    <h3>2. 曝光、對比、亮部和陰影</h3>
    <p>這些滑桿控制您影像的色調範圍——亮度和暗度。它們對於增加深度和衝擊力至關重要。</p>
    <ul>
        <li><strong>曝光：</strong>這是整個影像的主要亮度控制。如果整張照片太暗或太亮，請從這裡開始。</li>
        <li><strong>對比：</strong>這是您照片中亮部和暗部之間的差異。增加對比會使暗部更暗，亮部更亮，為影像增添「衝擊力」。減少對比可以創造出更平淡、更柔和的外觀。</li>
        <li><strong>亮部：</strong>此滑桿專門針對您影像中最亮的部分。如果您照片中的天空太亮，看起來像一團白色的斑點，您可以拉低亮部以恢復藍色和雲彩的細節。</li>
        <li><strong>陰影：</strong>這是亮部的相反。它專門針對您影像中最暗的部分。如果一個人的臉在陰影中看不清楚，您可以推高陰影滑桿以顯示其特徵，而不會使影像的其餘部分太亮。</li>
    </ul>

    <h3>3. 飽和度和自然飽和度：控制強度</h3>
    <p>一旦您的白平衡和色調範圍設定好，您就可以調整顏色本身的強度。</p>
    <ul>
        <li><strong>飽和度：</strong>此滑桿會統一增加您影像中每一種顏色的強度。請非常小心使用這個！推得太遠是初學者的典型錯誤，會導致不自然、像放射性物質般的顏色和斑駁的膚色。</li>
        <li><strong>自然飽和度：</strong>這是飽和度的「更聰明」版本。它主要增加您影像中最柔和顏色的強度，同時保持已經飽和的顏色不變。它在保護膚色不顯得不自然方面也做得更好。<strong>如有疑問，請使用自然飽和度而非飽和度。</strong></li>
    </ul>

    <h2>一個簡單的色彩校正工作流程</h2>
    <ol>
        <li><strong>步驟 1：修正白平衡。</strong>首先讓您的中性色正確。這是最重要的步驟。</li>
        <li><strong>步驟 2：調整曝光和對比。</strong>設定整體亮度並增加一些初步的衝擊力。</li>
        <li><strong>步驟 3：使用亮部和陰影進行微調。</strong>恢復最亮和最暗區域中任何丟失的細節。</li>
        <li><strong>步驟 4：使用自然飽和度增強色彩。</strong>在不過度操作的情況下，增加最後一抹色彩強度。謹慎使用飽和度，如果有的話。</li>
    </ol>

