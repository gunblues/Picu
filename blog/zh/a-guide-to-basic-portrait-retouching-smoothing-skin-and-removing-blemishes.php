    <p>人像是攝影中最強大的形式之一。一幅好的人像不僅捕捉到一個人的樣貌，還捕捉到他們的個性和情感。然而，現代相機的高解析度可能毫不留情，凸顯每一個微小的瑕疵、暫時的斑點和亂髮。這就是人像修圖發揮作用的地方。好的修圖目標不是讓某人看起來像另一個人，而是減少干擾，讓他們真實的自我得以展現。</p>
    <p>合乎道德的專業修圖是一門微妙的藝術。重點在於清理，而非掩蓋。本指南將引導您了解基本人像修圖的基礎技巧，著重於去除暫時性瑕疵和輕柔地撫平肌膚，以達到自然、精緻的效果。</p>

    <h2>理念：增強，而非抹去</h2>
    <p>在您接觸任何工具之前，重要的是要抱持正確的心態。目標不是創造一個塑膠般、完美無瑕的娃娃，而是要去除暫時性的干擾。一個好的經驗法則是，只去除那些兩週後就不會存在的東西。</p>
    <ul>
        <li><strong>要去除的東西：</strong>青春痘、粉刺、小刮痕、亂髮、衣服上的棉絮。</li>
        <li><strong>要保留（或僅柔化）的東西：</strong>永久性的特徵，如痣、疤痕和皺紋，這些是個人特質的一部分。抹去這些可能看起來不自然，甚至可能冒犯到拍攝對象。</li>
    </ul>

    <h2>工作工具：修復與仿製</h2>
    <p>要去除瑕疵，您主要會使用兩種工具。如果您的軟體允許非破壞性編輯，最好在一個獨立的圖層上進行這項工作。</p>

    <h3>1. 污點修復筆刷（您最好的朋友）</h3>
    <ul>
        <li><strong>它是什麼：</strong>這是最神奇且易於使用的修圖工具。您只需點擊一個瑕疵，工具就會智能地分析周圍的像素（紋理、顏色和亮度），並自動將瑕疵融合掉。</li>
        <li><strong>如何使用：</strong>讓您的筆刷比要去除的瑕疵稍大一點。點擊一次，看著它消失。對於大多數小而孤立的斑點，這是您唯一需要的工具。它快速、有效且出色。</li>
    </ul>

    <h3>2. 仿製印章工具</h3>
    <ul>
        <li><strong>它是什麼：</strong>仿製印章是一個更手動的工具。它允許您從影像的一個區域（來源）複製像素，並將它們繪製到另一個區域（目標）上。</li>
        <li><strong>如何使用：</strong>您首先必須按住一個鍵（通常是 Alt 或 Option）並點擊瑕疵附近一塊乾淨、紋理良好的皮膚區域來定義您的來源區域。然後，您將筆刷移到瑕疵上並點擊，將來源像素繪製在它上面。</li>
        <li><strong>何時使用：</strong>當污點修復筆刷感到困惑時，例如在非常靠近唇線或眉毛等硬邊緣工作時，仿製印章就很有用。它比自動工具提供更精確的控制。</li>
    </ul>

    <h2>皮膚平滑的藝術：紋理是關鍵</h2>
    <p>這是許多初學者犯下最大錯誤的地方：過度平滑皮膚，直到它失去所有自然的紋理。真實的皮膚有毛孔，完全抹去它們看起來既假又不專業。</p>

    <h3>錯誤的方法：模糊工具</h3>
    <p>切勿使用簡單的模糊工具來平滑皮膚。它只會將所有東西模糊在一起，破壞紋理，並導致那種可怕的塑膠感。</p>

    <h3>正確的方法：頻率分離（進階）vs. 紋理滑桿（簡單）</h3>
    <p><strong>頻率分離</strong>是 Photoshop 中使用的進階專業技術。它涉及將皮膚的顏色和紋理分離到兩個不同的圖層上，讓您可以平滑顏色和色調的過渡，而不會模糊細微的毛孔紋理。它提供最好的效果，但工作流程複雜。</p>
    <p>對於使用較簡單編輯器的人來說，一個現代而有效的替代方案是<strong>紋理</strong>滑桿。</p>
    <ul>
        <li><strong>紋理滑桿：</strong>許多現代編輯器現在都包含一個「紋理」或「清晰度」滑桿。紋理滑桿對皮膚特別有用。透過*減少*紋理滑桿一小部分（例如 -10 到 -25），您可以柔化皮膚並減少細紋和粗糙斑塊的出現，而不會破壞基本的毛孔結構。這是一種比簡單模糊更智能、更自然的方法。</li>
    </ul>
    <p><strong>工作流程：</strong>首先，用修復筆刷去除個別的瑕疵。然後，對整個臉部應用非常細微的負向紋理調整。如果您的工具允許，請使用遮色片將此平滑效果僅應用於皮膚，避開應保持銳利的眼睛、眉毛和嘴唇。</p>

    <h2>別忘了眼睛</h2>
    <p>在處理完皮膚後，對眼睛稍加注意可以使人像栩栩如生。</p>
    <ul>
        <li><strong>稍微提亮眼白：</strong>使用選擇性調整稍微增加眼白的亮度。不要讓它們變成純白色，只要稍微亮一點以減少任何泛黃或發紅。</li>
        <li><strong>銳化虹膜：</strong>僅對眼睛的虹膜應用少量選擇性銳化。這會創造一個焦點，使主體的凝視更具吸引力。</li>
    </ul>

    <h2>結論</h2>
    <p>好的人像修圖是一場微妙的舞蹈。關鍵在於知道該去除什麼和該保留什麼。透過使用正確的工具清理暫時的干擾，並應用溫和、注重紋理的平滑處理，您可以以一種既討喜又真實的方式增強主體的自然美。目標是讓觀者看到一張很棒的人物照片，而不是一張很棒的修圖照片。</p>

