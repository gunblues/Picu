    <h2>如何創建選擇性色彩效果</h2>
    <p>這種技術的專業方法涉及使用圖層遮罩，這為您提供了最大的控制權。以下是大多數現代照片編輯器中如何完成它的逐步指南。</p>
    <ol>
        <li><strong>步驟 1：選擇正確的照片。</strong>這種效果的最佳候選者是具有強烈、清晰定義的主體，且其顏色不會過多地滲入影像其餘部分的照片。一張紅色玫瑰在綠色背景前的照片比一輛紅色汽車旁邊是紅磚牆的照片是更好的選擇。</li>
        <li><strong>步驟 2：創建兩個圖層。</strong>您需要兩個版本的影像堆疊在一起。在您的編輯器中，創建您的照片的重複圖層。您應該有：
            <ul>
                <li>頂層（這將成為黑白版本）。</li>
                <li>底層（這將保持全彩）。</li>
            </ul>
        </li>
        <li><strong>步驟 3：將頂層去飽和。</strong>選擇頂層並將其轉換為黑白。為獲得最佳效果，請使用黑白混合器工具來控制顏色如何轉換為灰色，這將為您提供一個更豐富的單色影像。此時，您的整個影像將看起來是黑白的，因為頂層完全遮擋了下面的彩色圖層。</li>
        <li><strong>步驟 4：創建圖層遮罩。</strong>這是關鍵步驟。為您的頂層（黑白）圖層添加一個圖層遮罩。圖層遮罩就像一個模板。預設情況下，它將是白色的，表示整個黑白圖層是可見的。</li>
        <li><strong>步驟 5：用黑色繪畫以顯示顏色。</strong>現在，選擇畫筆工具並將其顏色設定為黑色。確保您正在遮罩上繪畫，而不是影像本身。當您在您想要顯示顏色的影像區域上繪畫時（例如，黃色計程車），您實際上是在黑白圖層中「挖一個洞」。這會顯示下面的原始全彩圖層。</li>
        <li><strong>步驟 6：細化您的遮罩。</strong>放大並使用較小的畫筆仔細繪製主體周圍的邊緣。如果您犯了錯誤並顯示了太多顏色，只需將畫筆顏色切換為白色，然後在該區域上重新繪製以恢復黑白效果。這種糾正錯誤的能力是使用遮罩優越的非破壞性方法的原因。</li>
        <li><strong>步驟 7：最終調整。</strong>一旦您對選擇感到滿意，您可以進行最終調整。您可能希望增加黑白圖層的對比度，或提高底層彩色圖層的自然飽和度，以使效果更具戲劇性。</li>
    </ol>

    <h2>有效使用選擇性色彩的技巧</h2>
    <ul>
        <li><strong>少即是多：</strong>當彩色物體相對較小，且場景的其餘部分在黑白中具有視覺趣味時，效果最強大。</li>
        <li><strong>講述一個故事：</strong>不要只因為能用就使用這種效果。思考您*為什麼*要突出該特定顏色。它是否增加了照片的故事或情感？</li>
        <li><strong>精確：</strong>花時間處理遮罩。顏色溢出線條的草率邊緣會立即讓效果看起來很業餘。使用柔邊畫筆以獲得更自然的過渡。</li>
        <li><strong>不要過度：</strong>因為這是一種非常風格化且流行的效果，它有時會顯得過時或陳腔濫調。在您的作品集中謹慎且有意識地使用它，以確保它保持其影響力。</li>
    </ul>

