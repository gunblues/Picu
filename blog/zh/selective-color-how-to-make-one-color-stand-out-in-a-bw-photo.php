        <li><strong>氛圍與象徵意義：</strong>色彩與情感息息相關。保留單一色彩可以為整個影像注入與該色彩相關的感覺。紅色物體可能象徵愛情、激情或危險。藍色物體可能感覺平靜或憂鬱。</li>
