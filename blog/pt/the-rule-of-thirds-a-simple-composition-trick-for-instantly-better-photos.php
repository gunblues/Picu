    <p>No mundo da fotografia e das artes visuais, existem alguns princípios fundamentais que podem melhorar drasticamente a qualidade do seu trabalho. Desses, nenhum é mais famoso ou mais eficaz do que a Regra dos Terços. É uma diretriz de composição simples e fácil de aprender que pode transformar suas fotos de meros instantâneos em imagens profissionais e cuidadosamente construídas. É a primeira técnica que todo fotógrafo aspirante deve aprender.</p>
