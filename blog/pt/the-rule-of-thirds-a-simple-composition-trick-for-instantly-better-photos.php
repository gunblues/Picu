    <h2>Lembre-se: É uma Diretriz, Não uma Lei</h2>
    <p>Como todas as "regras" artísticas, a Regra dos Terços deve ser uma diretriz, não uma lei rígida que nunca pode ser quebrada. Às vezes, um assunto perfeitamente centralizado é a escolha mais eficaz para uma foto específica, especialmente para criar uma sensação de simetria, estabilidade e direcionalidade. No entanto, você deve aprender a regra e praticá-la primeiro. Uma vez que você entenda *por que* ela funciona, você também entenderá quando é apropriado quebrá-la para um efeito criativo.</p>

