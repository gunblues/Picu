    <h3>3. समायोजन करना और प्रभाव लागू करना</h3>
    <p>पेशेवर संपादक शायद ही कभी समायोजन सीधे छवि पर लागू करते हैं। इसके बजाय, वे **समायोजन परतों** का उपयोग करते हैं। एक समायोजन परत एक विशेष प्रकार की परत होती है जिसमें पिक्सेल नहीं होते हैं, बल्कि निर्देश होते हैं (जैसे "कंट्रास्ट बढ़ाएं" या "रंग बदलें") और उन्हें उसके नीचे की सभी परतों पर लागू करते हैं।</p>
    <p>लाभ? यदि आप तय करते हैं कि आपको प्रभाव पसंद नहीं है, तो आप बस समायोजन परत को हटा सकते हैं, और आपकी मूल फोटो अछूती रहती है। आप इसकी अस्पष्टता को भी समायोजित कर सकते हैं। उदाहरण के लिए, आप एक काले और सफेद समायोजन परत जोड़ सकते हैं, फिर एक शांत, डीसैचुरेटेड रंग प्रभाव बनाने के लिए इसकी अस्पष्टता को 50% तक कम कर सकते हैं। आपके पास अनंत लचीलापन है।</p>

    <h3>4. पोर्ट्रेट को रीटच करना</h3>
    <p>एक पोर्ट्रेट को रीटच करते समय, एक सामान्य कार्यप्रवाह फोटो के ऊपर एक नई, खाली परत बनाना है। जब आपको एक दाग को हटाने की आवश्यकता होती है, तो आप त्वचा के एक साफ क्षेत्र का नमूना लेने और *नई परत* पर दाग पर पेंट करने के लिए एक हीलिंग या क्लोन टूल का उपयोग कर सकते हैं। इस तरह, आपके सभी संपादन मूल फोटो से अलग रखे जाते हैं। यदि आप कोई गलती करते हैं, तो आप रीटचिंग परत के उस हिस्से को मिटा देते हैं, न कि अपनी मूल छवि को।</p>

