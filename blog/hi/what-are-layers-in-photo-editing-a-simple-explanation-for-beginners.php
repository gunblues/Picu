    <p>परतों का समर्थन करने वाले किसी भी सॉफ्टवेयर में, आपको एक परत पैनल मिलेगा। इसमें आमतौर पर कुछ प्रमुख विशेषताएं होंगी:</p>
    <ul>
        <li><strong>परत स्टैक:</strong> आपकी सभी परतों की एक सूची, जिसमें शीर्ष परत सूची के शीर्ष पर होती है। आप उनके स्टैकिंग क्रम को बदलने के लिए परतों को ऊपर और नीचे खींच सकते हैं।</li>
        <li><strong>नई परत जोड़ें:</strong> एक नई, खाली परत बनाने के लिए एक बटन।</li>
        <li><strong>परत हटाएँ:</strong> चयनित परत को हटाने के लिए एक बटन।</li>
        <li><strong>अस्पष्टता:</strong> एक स्लाइडर जो नियंत्रित करता है कि एक परत कितनी पारदर्शी है। 100% पूरी तरह से अपारदर्शी है, जबकि 0% पूरी तरह से अदृश्य है।</li>
        <li><strong>दृश्यता (आँख का आइकन):</strong> एक परत के बगल में आँख आइकन पर क्लिक करने से यह अस्थायी रूप से छिप जाती है, जो एक संपादन के पहले और बाद के प्रभाव को देखने के लिए बहुत अच्छा है।</li>
