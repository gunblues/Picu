    <h2>कार्य के लिए उपकरण: हीलिंग और क्लोनिंग</h2>
    <p>दाग-धब्बे हटाने के लिए, आप मुख्य रूप से दो प्रकार के उपकरणों का उपयोग करेंगे। यदि आपका सॉफ्टवेयर गैर-विनाशकारी संपादन की अनुमति देता है तो इस काम को एक अलग परत पर करना सबसे अच्छा है।</p>

    <h3>1. स्पॉट हीलिंग ब्रश (आपका सबसे अच्छा दोस्त)</h3>
    <ul>
        <li><strong>यह क्या है:</strong> यह सबसे जादुई और उपयोग में आसान रीटचिंग उपकरण है। आप बस एक दाग पर क्लिक करते हैं, और उपकरण बुद्धिमानी से आसपास के पिक्सेल (बनावट, रंग और चमक) का विश्लेषण करता है और स्वचालित रूप से खामी को दूर कर देता है।</li>
        <li><strong>इसका उपयोग कैसे करें:</strong> अपने ब्रश को उस दाग से थोड़ा बड़ा करें जिसे आप हटाना चाहते हैं। एक बार क्लिक करें और इसे गायब होते देखें। अधिकांश छोटे, अलग-थलग धब्बों के लिए, यह एकमात्र उपकरण है जिसकी आपको आवश्यकता होगी। यह तेज़, प्रभावी और शानदार है।</li>
    </ul>

    <h3>2. क्लोन स्टैम्प टूल</h3>
    <ul>
        <li><strong>यह क्या है:</strong> क्लोन स्टैम्प एक अधिक मैनुअल उपकरण है। यह आपको छवि के एक क्षेत्र (स्रोत) से पिक्सेल कॉपी करने और उन्हें दूसरे क्षेत्र (लक्ष्य) पर पेंट करने की अनुमति देता है।</li>
        <li><strong>इसका उपयोग कैसे करें:</strong> आपको पहले अपनी स्रोत क्षेत्र को एक कुंजी (अक्सर Alt या Option) दबाकर और दाग के पास त्वचा के एक साफ, अच्छी बनावट वाले क्षेत्र पर क्लिक करके परिभाषित करना होगा। फिर, आप अपने ब्रश को दाग पर ले जाते हैं और स्रोत पिक्सेल को उस पर पेंट करने के लिए क्लिक करते हैं।</li>
        <li><strong>इसका उपयोग कब करें:</strong> क्लोन स्टैम्प तब उपयोगी होता है जब स्पॉट हीलिंग ब्रश भ्रमित हो जाता है, उदाहरण के लिए, जब होंठ रेखा या भौं जैसे कठोर किनारे के बहुत करीब काम कर रहे हों। यह आपको स्वचालित उपकरण की तुलना में अधिक सटीक नियंत्रण देता है।</li>
    </ul>

