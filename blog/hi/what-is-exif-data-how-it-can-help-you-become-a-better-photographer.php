                <li><strong>अपर्चर:</strong> आपके लेंस में खुलने का आकार (उदाहरण के लिए, f/1.8, f/8)।</li>
                <li><strong>शटर स्पीड:</strong> शटर खुला रहने की अवधि (उदाहरण के लिए, 1/1000s, 2s)।</li>
            </ul>
        </li>
