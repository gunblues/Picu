    <h2>तिहाई का नियम क्या है?</h2>
    <p>तिहाई का नियम बहुत सरल है। कल्पना कीजिए कि आपकी छवि को दो ऊर्ध्वाधर और दो क्षैतिज रेखाओं द्वारा नौ समान खंडों में विभाजित किया गया है, जैसे एक टिक-टैक-टो बोर्ड। नियम बताता है कि आपको अपने दृश्य में सबसे महत्वपूर्ण तत्वों को इन रेखाओं के साथ, या उन बिंदुओं पर रखना चाहिए जहाँ वे प्रतिच्छेद करते हैं। इन प्रतिच्छेदन बिंदुओं को अक्सर "शक्ति बिंदु" कहा जाता है।</p>
    <p>अधिकांश आधुनिक कैमरों और स्मार्टफोन ऐप्स में स्क्रीन पर 3x3 ग्रिड ओवरले प्रदर्शित करने का विकल्प होता है, जिससे शूटिंग करते समय इस नियम का अभ्यास करना अविश्वसनीय रूप से आसान हो जाता है।</p>

    <h2>यह क्यों काम करता है? नियम के पीछे का मनोविज्ञान</h2>
    <p>एक शुरुआती की स्वाभाविक प्रवृत्ति अपने विषय को सीधे फ्रेम के केंद्र में रखने की होती है। जबकि यह कभी-कभी समरूपता और स्थिरता की भावना पैदा करने के लिए प्रभावी हो सकता है, यह अक्सर एक ऐसी फोटो का परिणाम होता है जो स्थिर, उबाऊ और अनुमानित महसूस होती है।</p>
