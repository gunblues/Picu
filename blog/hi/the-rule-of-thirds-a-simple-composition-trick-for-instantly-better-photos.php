        <li><strong>यह आंख को घूमने के लिए प्रोत्साहित करता है:</strong> जब कोई विषय ऑफ-सेंटर होता है, तो दर्शक की आंख स्वाभाविक रूप से फ्रेम के चारों ओर घूमने के लिए प्रोत्साहित होती है, पूरे दृश्य की खोज करती है। एक केंद्रित विषय कभी-कभी आंख को अपनी जगह पर रोक सकता है।</li>
        <li><strong>यह एक अधिक प्राकृतिक भावना पैदा करता है:</strong> नियम ऐसी संरचनाएं बनाने में मदद करता है जो अधिक प्राकृतिक और कम मंचित महसूस होती हैं। यह विषय को अपने वातावरण में मौजूद रहने की अनुमति देता है बजाय एक स्थिर बुलसी के।</li>
