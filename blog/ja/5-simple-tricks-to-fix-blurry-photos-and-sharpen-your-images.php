    <p>写真撮影において、完璧な瞬間を捉えたと思ったのに、後で確認すると画像がソフトだったり、わずかにピントがずれていたり、ぼやけていたりすることほどがっかりすることはありません。ぼやけた写真は、カメラの揺れ、被写体の動き、ピントのずれ、あるいは画像のサイズ変更後に発生する自然なソフトさなど、さまざまな理由で発生します。完全にピントがずれたショットを魔法のように修正することはできませんが、少しソフトな写真を救い出し、大幅に改善することは間違いなく可能です。</p>
