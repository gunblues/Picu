    <h2>避けるべき一般的な間違い</h2>
    <ul>
        <li><strong>同じ画像を複数回リサイズする：</strong>JPGをリサイズして保存するたびに、圧縮により品質が少しずつ失われます。常に元の高解像度ファイルのコピーでリサイズを実行してください。</li>
        <li><strong>小さな画像を拡大する：</strong>100x100ピクセルのサムネイルを全画面の傑作に変えることを期待しないでください。それは機能しません。より大きなソース画像を見つけてください。</li>
        <li><strong>HTML/CSSにリサイズを頼る：</strong>一般的なウェブ開発の間違いは、巨大な4000pxの画像をアップロードし、HTMLまたはCSSでその幅を`<img src="huge-image.jpg" width="500">`のように設定することです。これはページ上では正しく見えますが、ユーザーのブラウザは依然として巨大な元のファイルをダウンロードする必要があり、ウェブサイトの速度を大幅に低下させます。常にアップロード*する前に*画像を正しい寸法にリサイズしてください。</li>
    </ul>

