    <h2>問題の理解：露出とは何か？</h2>
    <p>露出とは、写真を撮るときにカメラセンサーに到達する光の総量のことです。</p>
    <ul>
        <li><strong>露出不足：</strong>センサーに十分な光が到達しなかった。結果として、暗い画像になり、シャドウのディテールが失われる。露出不足の画像のヒストグラムは左側に集中する。</li>
        <li><strong>露出過度：</strong>センサーに光が到達しすぎた。結果として、過度に明るい画像になり、ハイライト（画像の最も明るい部分）のディテールが失われる。露出過度の画像のヒストグラムは右側に集中する。</li>
    </ul>
    <p>私たちの目標は、編集ツールを使用してこの光の情報を再分配し、自然で細部まで表現されたバランスの取れた画像を作成することです。</p>

    <h2>露出修正のための必須ツールキット</h2>
    <p>何十もの複雑なツールは必要ありません。ほとんどすべての写真編集ソフトにあるいくつかの主要なスライダーで、作業の99%をこなすことができます。</p>

    <h3>1. 露出不足の写真（暗すぎる）の場合</h3>
    <p>写真が暗すぎる場合、主な目標は、画像が平坦になったりノイズが多くなったりすることなく、より多くの光を取り入れることです。</p>
    <ol>
        <li><strong>露出スライダーから始める：</strong>これがあなたのマスターコントロールです。メインの被写体が十分に明るくなるまで、露出をゆっくりと上げて画像全体の明るさを上げます。</li>
        <li><strong>シャドウを持ち上げる：</strong>露出を上げた後も、画像の最も暗い部分がまだ濁って見えるかもしれません。<strong>シャドウ</strong>スライダーを使用して、これらの暗い部分を特にターゲットにして明るくします。これは、すでに十分に明るい画像の部分に影響を与えることなく、シャドウに隠されたディテールを明らかにする素晴らしいツールです。</li>
        <li><strong>黒を調整する：</strong>シャドウを持ち上げると、画像内の最も暗い点が乳白色の灰色に見えることがあります。深い豊かな黒点を復元するには、<strong>黒</strong>スライダーをわずかに下げます。これによりコントラストが追加され、画像が色あせて見えるのを防ぎます。</li>
        <li><strong>ノイズに注意する：</strong>非常に暗い写真を大幅に明るくすると、デジタル「ノイズ」または粒状感が発生し、細かい斑点のように見えます。これが発生した場合は、ノイズリダクションツールを使用して滑らかにしますが、プラスチックのような外観を避けるために控えめに適用してください。</li>
    </ol>

    <h3>2. 露出過度の写真（明るすぎる）の場合</h3>
    <p>写真が明るすぎる場合、目標は、画像がくすんだり灰色になったりすることなく、ハイライトで失われたディテールを回復することです。</p>
    <ol>
        <li><strong>露出スライダーから始める：</strong>露出をゆっくりと下げて、全体的な明るさを下げ、画像を通常の範囲に戻します。</li>
        <li><strong>ハイライトを救う：</strong>これが最も重要なステップです。露出過度の写真には、空や白いシャツのような明るい部分が純粋な白でテクスチャがない「白飛び」したハイライトがよくあります。<strong>ハイライト</strong>スライダーを使用して、これらの明るい部分を特にターゲットにして暗くします。空の青い色やウェディングドレスのテクスチャなど、どれだけのディテールを回復できるかに驚くことでしょう。</li>
        <li><strong>白を調整する：</strong>黒スライダーと同様に、<strong>白</strong>スライダーは画像の最も明るい点を設定します。ハイライトのディテールを回復した後、画像の中で*明るくあるべき*部分が清潔で明るい感じを保つように、白スライダーをわずかに上げる必要があるかもしれません。</li>
        <li><strong>コントラストを少し戻す：</strong>露出とハイライトを下げると、画像が少し平坦に見えることがあります。プロセスの最後に<strong>コントラスト</strong>スライダーを少し上げることで、良い深みを取り戻すことができます。</li>
    </ol>

    <h2>RAWファイルの力</h2>
    <p>JPGを修正することはできますが、RAWファイルはこれらの種類の修正に対してはるかに広い許容範囲を提供します。RAWファイルは、カメラのセンサーによってキャプチャされたすべてのデータを含む非圧縮ファイルです。一方、JPGは、カメラがすでに決定を下し、そのデータの一部を破棄した圧縮ファイルです。これは、RAWファイルが極端なシャドウとハイライトに隠されたはるかに多くのディテールを保持していることを意味し、成功した回復の可能性がはるかに高くなります。</p>

