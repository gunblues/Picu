    <p>屋内で写真を撮ったら、奇妙なオレンジ色になったり、日陰で写真を撮ったら、不自然な青色になったりした経験はありませんか？この一般的な問題は、ホワイトバランスの誤りが原因です。私たちの脳は、さまざまな種類の光に自動的に適応する能力が驚くほど優れているため、ランプの暖かい光の下でも、曇りの日の涼しい光の下でも、白い紙を白として認識します。しかし、デジタルカメラはそれほど賢くありません。光をそのまま記録するだけで、しばしば不要な色かぶりが発生します。</p>
    <p>ホワイトバランス補正とは、これらの非現実的な色かぶりを取り除き、実際に白く見えるオブジェクトが写真でも白くレンダリングされるようにするプロセスです。これは色補正の絶対的な基礎です。ホワイトバランスが間違っていると、写真の他のすべての色も間違ってしまいます。この簡単な調整を習得することは、画像で自然で正確で美しい色を実現するための最初で最も重要なステップです。</p>

    <h2>色温度を理解する</h2>
    <p>ホワイトバランスの背後にある中心的な概念は<strong>色温度</strong>です。異なる光源は異なる色の光を生成します。この色はケルビン（K）スケールと呼ばれるスケールで測定されます。</p>
    <ul>
        <li><strong>暖かい光（低ケルビン）：</strong>ろうそくの炎や従来のタングステン電球は、非常に暖かく、オレンジがかった黄色の光を生成します。これはスケールの下端（約1000-3000K）です。</li>
        <li><strong>中性光（真昼の太陽）：</strong>真昼の直射日光は、比較的中性または「白い」光と見なされます（約5500K）。</li>
        <li><strong>冷たい光（高ケルビン）：</strong>曇りの日や日陰の光は、実際には青みがかった、または冷たい色調です。これはスケールの上端（約6500-10,000K）です。</li>
    </ul>
    <p>ホワイトバランス設定の役割は、光源の色温度を補償して、中性な画像を生成することです。暖かい光で撮影している場合、カメラはオレンジを中和するために青を追加する必要があります。冷たい光で撮影している場合、カメラは青を中和するために黄色/オレンジを追加する必要があります。</p>

    <h2>ホワイトバランス補正のツール</h2>
    <p>写真編集ソフトでは、通常、ホワイトバランスを調整するための3つの主要なツールがあります。</p>

    <h3>1. ホワイトバランスプリセット</h3>
    <p>ほとんどのエディターには、カメラで見られる設定に一致するプリセットのドロップダウンメニューがあります。これには、「昼光」、「曇り」、「日陰」、「タングステン」、「蛍光灯」などのオプションが含まれます。写真が撮影された照明条件を知っていれば、対応するプリセットを選択するだけで、すぐに正しい結果に非常に近づくことができます。たとえば、屋内の写真がオレンジ色に見える場合、「タングステン」プリセットを選択すると、自動的に青が追加されて打ち消されます。</p>

    <h3>2. 色温度と色合いのスライダー</h3>
    <p>これらのスライダーは、色を微調整するための手動コントロールを提供します。</p>
    <ul>
        <li><strong>色温度：</strong>これは主要なスライダーです。青から黄色の軸に沿って色を調整します。画像が青すぎる場合は、スライダーを黄色側に移動して暖めます。画像がオレンジすぎる場合は、スライダーを青色側に移動して冷まします。</li>
        <li><strong>色合い：</strong>このスライダーは、緑からマゼンタの軸に沿って色を調整します。これは、より珍しい光源、特に蛍光灯による色かぶりを補正するために使用されます。蛍光灯はしばしば緑がかった色かぶりを生成することがあります。色温度を補正しても写真がまだ少し「おかしい」場合は、色合いスライダーを少し調整するのが解決策となることがよくあります。</li>
    </ul>

    <h3>3. ホワイトバランスセレクター（スポイトツール）</h3>
    <p>これは、ホワイトバランスを設定する最も速く、しばしば最も正確な方法です。スポイトツールを使用すると、ソフトウェアに何が中性色であるべきかを伝えることができます。</p>
    <ol>
        <li><strong>ツールを選択する：</strong>ホワイトバランスパネルでスポイトアイコンを見つけて選択します。</li>
        <li><strong>中性点を見つける：</strong>写真の中で、白、中間灰色、または黒のいずれかであるべき中性色であると確信できるオブジェクトを探します。白いシャツ、灰色の歩道、誰かの目の白目、値札などが良い候補です。</li>
        <li><strong>中性点をクリックする：</strong>スポイトでその中性点をクリックします。ソフトウェアは、クリックしたピクセルの色を自動的に分析し、そのピクセルが完全に中性になるように色温度と色合いのスライダーを即座に調整します。</li>
    </ol>
    <p>ソフトウェアは「真の中性」が何であるかを知っているため、画像内の他のすべての色を正確に再マッピングし、ワンクリックで写真全体から色かぶりを取り除くことができます。これは強力で信じられないほど効率的なツールです。</p>

    <h2>シンプルなホワイトバランスワークフロー</h2>
    <ol>
        <li><strong>まずスポイトを試す：</strong>画像の中性点をスキャンします。見つかれば、スポイトツールが正確な結果への最速の道です。</li>
        <li><strong>中性点が存在しない場合はプリセットを使用する：</strong>写真に明らかな中性色がない場合（例：夕焼けや森のシーン）、覚えている照明条件に基づいてプリセットを適用してみてください。</li>
        <li><strong>スライダーで微調整する：</strong>スポイトまたはプリセットを使用した後、色温度と色合いのスライダーを使用して、独自の創造的な判断に基づいて、小さく最終的な調整を行います。創造的な効果のために、シーンをわずかに暖かくしたり、冷たくしたりしたい場合があります。</li>
    </ol>

