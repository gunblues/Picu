    <h2>三分割法とは？</h2>
    <p>三分割法は非常にシンプルです。画像を2本の垂直線と2本の水平線で9つの等しいセグメントに分割すると想像してください。まるで三目並べの盤のようです。このルールは、シーンの最も重要な要素をこれらの線に沿って、またはそれらが交差する点に配置することを提案しています。これらの交点はしばしば「パワーポイント」と呼ばれます。</p>
    <p>ほとんどの最新のカメラやスマートフォンアプリには、画面に3x3のグリッドオーバーレイを表示するオプションがあり、撮影中にこのルールを練習するのが非常に簡単になります。</p>

    <h2>なぜ機能するのか？ルールの背後にある心理学</h2>
    <p>初心者の自然な傾向は、被写体をフレームの真ん中に配置することです。これは対称性と安定感を生み出すのに効果的な場合もありますが、多くの場合、静的で退屈で予測可能な写真になってしまいます。</p>
    <p>三分割法に従って、被写体を中央から外れた位置に配置すると、よりダイナミックで視覚的に興味深い構図が作成されます。理由は次のとおりです。</p>
    <ul>
        <li><strong>バランスと緊張感を生み出す：</strong>被写体をフレームの片側に配置することで、反対側に「ネガティブスペース」の感覚を生み出します。被写体とネガティブスペースのこの相互作用は、視覚的な緊張感とバランスを生み出し、見る人にとってより魅力的です。</li>
        <li><strong>目の動きを促す：</strong>被写体が中央から外れている場合、見る人の目は自然にフレーム内を動き回り、シーン全体を探索するように促されます。中央に配置された被写体は、時には目の動きを止めてしまうことがあります。</li>
        <li><strong>より自然な感覚を生み出す：</strong>このルールは、より自然で演出されていない構図を作成するのに役立ちます。被写体が静的な的ではなく、その環境の中に存在することを可能にします。</li>
    </ul>

    <h2>三分割法を実践で適用する方法</h2>
    <p>さまざまな種類の写真でグリッドを使用する方法を見てみましょう。</p>

    <h3>風景の場合：</h3>
    <ul>
        <li>水平線を写真の真ん中に直接配置するのではなく、上または下の水平線に沿って配置します。</li>
        <li><strong>どの線を選択すべきか？</strong>何がより興味深いかによって異なります。劇的で美しい空がある場合は、水平線を下の線に配置して、フレームの3分の2を空に割り当てます。前景がより興味深い場合（花畑やテクスチャのあるビーチなど）は、水平線を上の線に配置して、陸地を強調します。</li>
    </ul>

    <h3>ポートレートの場合：</h3>
    <ul>
        <li>被写体を左または右の垂直線に沿って配置します。</li>
        <li>最も重要な特徴、通常は目を、上部の交点のいずれかに配置します。これにより、強力な焦点が作成されます。</li>
        <li>被写体をネガティブスペースの方を見たり、移動させたりします。たとえば、人物が左の垂直線上にいる場合、フレームの右側を見るべきです。これにより、期待感が生じ、被写体に「呼吸の空間」が与えられます。</li>
    </ul>

    <h3>動く被写体の場合：</h3>
    <ul>
        <li>車やランナーのような動く被写体を撮影している場合は、それらを垂直線の1つに配置し、移動方向の前に空白スペースを残します。これにより、見る人は被写体がどこに向かっているのかを理解し、動きの感覚を生み出します。</li>
    </ul>

