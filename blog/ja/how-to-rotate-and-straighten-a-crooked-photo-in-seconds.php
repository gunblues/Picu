    <p>高度なデスクトップソフトウェアからPicuのようなシンプルなオンラインツールまで、ほとんどすべての写真編集ソフトには、回転とまっすぐにするための直感的な機能があります。</p>

    <h3>方法1：シンプルな90度回転</h3>
    <p>これは最も基本的な回転形式で、写真が完全に横向きまたは逆さまになっている場合に使用します。これは、携帯電話からコンピューターに写真を転送したときに、向きのメタデータが正しく読み取られない場合に頻繁に発生します。</p>
    <ul>
        <li><strong>仕組み：</strong>正方形を回転させる矢印を示すアイコンを探します。通常、「左回転」と「右回転」のボタンがあります。</li>
        <li><strong>いつ使用するか：</strong>写真が横向きの場合。1回または2回クリックするだけで、正しい向きに瞬時に反転します（例：横向きから縦向きへ）。</li>
    </ul>

    <h3>方法2：まっすぐにするスライダーで微調整</h3>
    <p>これは、わずかな、意図しない傾きを修正するために使用するツールです。正確な、度単位の調整が可能です。</p>
    <ol>
        <li><strong>画像をアップロードする：</strong>歪んだ写真をエディターで開きます。</li>
        <li><strong>まっすぐにするツールを見つける：</strong>これは、グリッドと湾曲した矢印を示すアイコンで表されることが多く、またはトリミングツールと一緒に見つかります。</li>
        <li><strong>スライダーを使用する：</strong>通常、-45度から+45度の範囲のスライダーが表示されます。スライダーを動かすと、画像にグリッドオーバーレイが表示されます。スライダーを左右にドラッグし、グリッド線を確認します。目標は、グリッドの水平線を写真の水平線に合わせるか、グリッドの垂直線を建物やその他の直立したオブジェクトに合わせることです。</li>
        <li><strong>自動トリミング：</strong>画像を回転させると、角が切り取られ、空白のスペースが残ります。ほとんどの最新のエディターは、これらの空白の角を排除するために可能な限り最大のトリミングを自動的に計算し、完璧な長方形の、まっすぐな画像を提供します。</li>
        <li><strong>確認して保存する：</strong>線が平行になったら、変更を適用します。これで写真のバランスが完璧になりました。</li>
    </ol>

