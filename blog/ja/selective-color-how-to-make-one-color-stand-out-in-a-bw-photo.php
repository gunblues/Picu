    <h2>選択的カラー効果を作成する方法</h2>
    <p>このテクニックのプロフェッショナルな方法は、レイヤーマスクを使用することを含み、これにより最大のコントロールが得られます。ほとんどの最新の写真編集ソフトでどのように行われるかのステップバイステップガイドです。</p>
    <ol>
        <li><strong>ステップ1：適切な写真を選択する。</strong>この効果に最適な候補は、明確に定義された強い被写体で、残りの画像にあまり色がにじまない、明確な色を持つ画像です。緑の背景に対する赤いバラの写真は、赤いレンガの壁の隣にある赤い車の写真よりも良い選択です。</li>
        <li><strong>ステップ2：2つのレイヤーを作成する。</strong>画像を重ねて2つのバージョンを作成する必要があります。エディターで、写真の複製レイヤーを作成します。次のようになります。
            <ul>
                <li>トップレイヤー（白黒バージョンになります）。</li>
                <li>ボトムレイヤー（フルカラーのままになります）。</li>
            </ul>
        </li>
        <li><strong>ステップ3：トップレイヤーを彩度を下げる。</strong>トップレイヤーを選択し、白黒に変換します。最高の結果を得るには、白黒ミキサーツールを使用して、色がどのように灰色に変換されるかを制御し、より豊かなモノクロ画像を作成します。この時点では、トップレイヤーが下のカラーレイヤーを完全に覆い隠しているため、画像全体が白黒に見えます。</li>
        <li><strong>ステップ4：レイヤーマスクを作成する。</strong>これが重要なステップです。トップ（白黒）レイヤーにレイヤーマスクを追加します。レイヤーマスクはステンシルのようなものです。デフォルトでは白で、白黒レイヤー全体が表示されます。</li>
        <li><strong>ステップ5：黒でペイントして色を明らかにする。</strong>次に、ブラシツールを選択し、色を黒に設定します。画像自体ではなく、*マスク*にペイントしていることを確認してください。色を表示したい画像の領域（例：黄色いタクシー）にペイントすると、白黒レイヤーに「穴を開ける」ことになります。これにより、その下にある元のフルカラーレイヤーが明らかになります。</li>
        <li><strong>ステップ6：マスクを微調整する。</strong>ズームインし、小さなブラシを使用して、被写体のエッジを慎重にペイントします。間違いを犯して色を露出しすぎた場合は、ブラシの色を白に切り替えて、その領域を再度ペイントするだけで、白黒効果を復元できます。間違いを修正できるこの能力が、マスクを使用することが優れた非破壊的な方法である理由です。</li>
        <li><strong>ステップ7：最終調整。</strong>選択に満足したら、最終調整を行うことができます。白黒レイヤーのコントラストを上げたり、下のカラーレイヤーの自然な彩度を上げて、効果をさらに劇的にしたいと思うかもしれません。</li>
    </ol>

