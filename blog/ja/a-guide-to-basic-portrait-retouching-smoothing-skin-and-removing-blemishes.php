    <h2>作業ツール：ヒーリングとクローン</h2>
    <p>シミを取り除くには、主に2種類のツールを使用します。ソフトウェアが非破壊編集を許可している場合は、別のレイヤーでこの作業を行うのが最適です。</p>

    <h3>1. スポット修復ブラシ（あなたの親友）</h3>
    <ul>
        <li><strong>これは何ですか：</strong>これは最も魔法のような、使いやすいレタッチツールです。シミをクリックするだけで、ツールは周囲のピクセル（テクスチャ、色、明るさ）をインテリジェントに分析し、自動的に欠陥をブレンドして消し去ります。</li>
        <li><strong>使用方法：</strong>ブラシを削除したいシミよりわずかに大きくします。一度クリックすると、それが消えます。ほとんどの小さな孤立した斑点には、これだけが必要なツールです。高速で効果的で、素晴らしいです。</li>
    </ul>

    <h3>2. クローンスタンプツール</h3>
    <ul>
        <li><strong>これは何ですか：</strong>クローンスタンプは、より手動のツールです。画像の1つの領域（ソース）からピクセルをコピーし、別の領域（ターゲット）にペイントすることができます。</li>
        <li><strong>使用方法：</strong>まず、キー（通常はAltまたはOption）を押しながら、シミの近くの清潔でテクスチャの整った肌の領域をクリックして、ソース領域を定義する必要があります。次に、ブラシをシミの上に移動し、クリックしてソースピクセルをその上にペイントします。</li>
        <li><strong>いつ使用するか：</strong>クローンスタンプは、スポット修復ブラシが混乱する場合、たとえば、唇のラインや眉毛のような硬いエッジの非常に近くで作業する場合に役立ちます。自動ツールよりも正確なコントロールを提供します。</li>
    </ul>

    <h2>肌を滑らかにする技術：テクスチャが鍵</h2>
    <p>これは多くの初心者が最大の過ちを犯す場所です。肌の自然なテクスチャをすべて失うまで肌を過度に滑らかにしてしまうことです。実際の肌には毛穴があり、それらを完全に消去すると、偽物でプロフェッショナルではないように見えます。</p>

    <h3>間違った方法：ぼかしツール</h3>
    <p>肌を滑らかにするために、単純なぼかしツールを使用しないでください。それはすべてをぼかし、テクスチャを破壊し、その恐ろしいプラスチックのような外観をもたらします。</p>

    <h3>正しい方法：周波数分離（高度）vs. テクスチャスライダー（シンプル）</h3>
    <p><strong>周波数分離</strong>は、Photoshopで使用される高度なプロフェッショナルなテクニックです。肌の色とテクスチャを2つの異なるレイヤーに分離し、細かい毛穴のテクスチャをぼかすことなく、色とトーンの移行を滑らかにすることができます。最高の結果を提供しますが、複雑なワークフローです。</p>
    <p>よりシンプルなエディターを使用している人にとって、現代的で効果的な代替手段は<strong>テクスチャ</strong>スライダーです。</p>
    <ul>
        <li><strong>テクスチャスライダー：</strong>多くの最新のエディターには、「テクスチャ」または「明瞭度」スライダーが含まれています。テクスチャスライダーは、肌に特に役立ちます。テクスチャスライダーを少量（例：-10〜-25）*減らす*ことで、肌を柔らかくし、基本的な毛穴の構造を破壊することなく、小じわや粗い部分の見た目を減らすことができます。これは、単純なぼかしよりもはるかにインテリジェントで自然なアプローチです。</li>
    </ul>
    <p><strong>ワークフロー：</strong>まず、ヒーリングブラシで個々のシミを取り除きます。次に、顔全体に非常に微妙な負のテクスチャ調整を適用します。ツールが許す場合は、このスムージング効果を肌にのみ適用するためにマスクを使用し、シャープなままであるべき目、眉毛、唇を避けます。</p>

    <h2>目を忘れないでください</h2>
    <p>肌の作業が終わったら、目に少し注意を払うと、ポートレートが生き生きとします。</p>
    <ul>
        <li><strong>白目をわずかに明るくする：</strong>選択的な調整を使用して、白目の明るさをわずかに上げます。純粋な白にしないでください。黄ばみや赤みを減らすために、少し明るくするだけです。</li>
        <li><strong>虹彩をシャープにする：</strong>目の虹彩にのみ、少量の選択的なシャープ化を適用します。これにより、焦点が作成され、被写体の視線がより魅力的になります。</li>
    </ul>

