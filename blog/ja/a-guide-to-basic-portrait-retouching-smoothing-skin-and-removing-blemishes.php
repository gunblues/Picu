    <p>ツールに触れる前に、正しい考え方を持つことが重要です。目標は、プラスチックのような完璧な人形を作ることではありません。目標は、一時的な邪魔な要素を取り除くことです。良い経験則は、2週間後にはそこにはないものだけを取り除くことです。</p>
