    <p>비파괴 편집은 단순히 개념이 아닙니다. 사진 편집 소프트웨어의 특정 기능에 의해 가능해집니다.</p>

    <h3>1. 레이어</h3>
    <p>이것은 가장 기본적인 비파괴 도구입니다. 모든 변경 사항을 단일 배경 이미지에 적용하는 대신, 편집 내용을 별도의 투명 레이어에 쌓습니다.</p>
    <ul>
        <li><strong>예시:</strong> 사진에 텍스트를 추가하고 싶다고 가정해 봅시다. 이미지에 직접 입력하고 저장하면 텍스트는 픽셀에 영구적으로 기록됩니다. 사진 위에 새 레이어에 텍스트를 추가하면, 아래 사진에 영향을 주지 않고 나중에 이동하거나, 글꼴을 변경하거나, 삭제할 수 있습니다.</li>
    </ul>

    <h3>2. 조정 레이어</h3>
    <p>이것은 색상 및 톤 변경을 위한 전문가의 선택 도구입니다. 조정 레이어는 픽셀을 포함하지 않고, 지침(예: "대비 20% 증가", "이미지를 흑백으로 만들기")을 포함하고 그 아래의 모든 레이어에 적용되는 특수 유형의 레이어입니다.</p>
    <p>이점은 무엇입니까? 효과가 마음에 들지 않으면 조정 레이어를 삭제하기만 하면 원본 사진이 손상되지 않고 즉시 원래 색상으로 되돌아갑니다. 또는 조정 레이어의 불투명도를 50%로 낮춰 차분하고 채도가 낮은 색상 효과를 만들 수도 있습니다. 무한한 유연성을 가질 수 있습니다.</p>

    <h3>3. 레이어 마스크</h3>
    <p>마스크는 레이어와 조정 레이어를 진정으로 강력하게 만드는 요소입니다. 마스크는 레이어에 연결되어 가시성을 제어합니다. 마스크에서는 흰색 또는 검은색으로 칠할 수 있습니다. 마스크가 흰색인 부분은 레이어가 보이고, 마스크가 검은색인 부분은 레이어가 숨겨집니다(투명).</p>
    <ul>
        <li><strong>예시:</strong> 인물 사진에 선명화 조정 레이어를 추가했다고 가정해 봅시다. 하지만 피부가 아닌 눈만 선명하게 하고 싶습니다. 조정 레이어에 검은색 마스크를 추가하고(효과를 완전히 숨김), 흰색 브러시를 사용하여 마스크의 눈 부분만 칠합니다. 이렇게 하면 해당 특정 영역에서만 선명화 효과가 나타납니다. 이는 로컬 조정을 적용하는 비파괴적인 방법입니다.</li>
    </ul>

