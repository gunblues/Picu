    <h3>1. 노출 부족 사진 (너무 어두움)의 경우</h3>
    <p>사진이 너무 어두울 때, 주요 목표는 이미지를 평평하거나 노이즈가 많게 만들지 않고 더 많은 빛을 도입하는 것입니다.</p>
    <ol>
        <li><strong>노출 슬라이더부터 시작:</strong> 이것이 마스터 컨트롤입니다. 메인 피사체가 잘 조명될 때까지 노출을 부드럽게 높여 이미지의 전체 밝기를 높입니다.</li>
        <li><strong>그림자 올리기:</strong> 노출을 높인 후에도 이미지의 가장 어두운 부분이 여전히 흐릿하게 보일 수 있습니다. <strong>그림자</strong> 슬라이더를 사용하여 이러한 어두운 영역을 특별히 대상으로 하여 밝게 합니다. 이것은 이미 충분히 밝은 이미지 부분에 영향을 미치지 않고 그림자에 숨겨진 디테일을 드러내는 환상적인 도구입니다.</li>
        <li><strong>검은색 조정:</strong> 그림자를 올리면 때때로 이미지에서 가장 어두운 지점이 풍부한 검은색 대신 우유빛 회색처럼 보일 수 있습니다. 깊고 풍부한 검은색 지점을 복원하려면 <strong>검은색</strong> 슬라이더를 약간 줄이십시오. 이렇게 하면 대비가 추가되고 이미지가 색이 바랜 것처럼 보이는 것을 방지합니다.</li>
        <li><strong>노이즈에 유의:</strong> 매우 어두운 사진을 급격하게 밝게 하면 디지털 "노이즈" 또는 입자가 발생하여 미세한 반점처럼 보일 수 있습니다. 이런 일이 발생하면 노이즈 감소 도구를 사용하여 부드럽게 하십시오. 그러나 플라스틱 같은 모양을 피하기 위해 아껴서 적용하십시오.</li>
    </ol>

    <h3>2. 과다 노출 사진 (너무 밝음)의 경우</h3>
    <p>사진이 너무 밝을 때, 목표는 이미지를 칙칙하거나 회색으로 만들지 않고 하이라이트에서 손실된 디테일을 복구하는 것입니다.</p>
    <ol>
        <li><strong>노출 슬라이더부터 시작:</strong> 노출을 부드럽게 줄여 전체 밝기를 낮추고 이미지를 정상 범위로 되돌립니다.</li>
        <li><strong>하이라이트 복구:</strong> 이것이 가장 중요한 단계입니다. 과다 노출된 사진은 종종 "날아간" 하이라이트를 가지고 있습니다. 하늘이나 흰색 셔츠와 같은 밝은 영역이 질감 없이 순수한 흰색입니다. <strong>하이라이트</strong> 슬라이더를 사용하여 이러한 밝은 영역을 특별히 대상으로 하여 어둡게 합니다. 하늘의 파란색이나 웨딩드레스의 질감과 같은 얼마나 많은 디테일을 복구할 수 있는지에 놀랄 것입니다.</li>
        <li><strong>흰색 조정:</strong> 검은색 슬라이더와 유사하게, <strong>흰색</strong> 슬라이더는 이미지에서 가장 밝은 지점을 설정합니다. 하이라이트 디테일을 복구한 후, 이미지에서 *밝아야 할* 부분이 여전히 깨끗하고 밝은 느낌을 갖도록 흰색 슬라이더를 약간 늘려야 할 수 있습니다.</li>
        <li><strong>대비 약간 추가:</strong> 노출과 하이라이트를 낮추면 때때로 이미지가 약간 평평하게 보일 수 있습니다. 프로세스 끝에 <strong>대비</strong> 슬라이더를 약간 높이면 좋은 깊이감을 복원할 수 있습니다.</li>
    </ol>

    <h2>RAW 파일의 힘</h2>
    <p>JPG를 확실히 살릴 수 있지만, RAW 파일은 이러한 종류의 보정에 훨씬 더 많은 여유를 제공합니다. RAW 파일은 카메라 센서가 캡처한 모든 데이터를 포함하는 비압축 파일입니다. 반면에 JPG는 카메라가 이미 결정을 내리고 일부 데이터를 버린 압축 파일입니다. 이는 RAW 파일이 극단적인 그림자와 하이라이트에 훨씬 더 많은 숨겨진 디테일을 가지고 있어 성공적인 복구 가능성이 훨씬 더 높다는 것을 의미합니다.</p>

