    <h2>문제 이해: 노출이란 무엇인가?</h2>
    <p>노출은 단순히 사진을 찍을 때 카메라 센서에 도달하도록 허용되는 총 빛의 양입니다.</p>
    <ul>
        <li><strong>노출 부족:</strong> 센서에 충분한 빛이 도달하지 못했습니다. 결과는 그림자에서 디테일이 손실된 어두운 이미지입니다. 노출 부족 사진의 히스토그램은 왼쪽에 뭉쳐져 있습니다.</li>
        <li><strong>과다 노출:</strong> 센서에 너무 많은 빛이 도달했습니다. 결과는 하이라이트(이미지의 가장 밝은 부분)에서 디테일이 손실된 지나치게 밝은 이미지입니다. 과다 노출 사진의 히스토그램은 오른쪽에 뭉쳐져 있습니다.</li>
    </ul>
    <p>우리의 목표는 편집 도구를 사용하여 이 빛 정보를 재분배하여 자연스럽고 디테일이 풍부한 균형 잡힌 이미지를 만드는 것입니다.</p>

