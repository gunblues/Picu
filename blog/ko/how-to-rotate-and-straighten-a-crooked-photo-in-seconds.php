    <p>우리 뇌는 균형과 질서를 추구하도록 자연적으로 연결되어 있습니다. 우리는 수평선(지평선과 같은)이 수평이고 수직선(건물과 같은)이 수직이기를 기대합니다. 사진에서 이러한 선이 기울어지면 불안감이나 긴장감을 유발합니다. 의도적인 기울기(종종 "더치 앵글"이라고 불림)는 드라마나 방향 감각 상실의 느낌을 만들기 위한 예술적 효과로 사용될 수 있지만, 의도하지 않은 기울기는 단순히 실수처럼 보입니다.</p>
