    <h2>색상의 구성 요소: 주요 조정</h2>
    <p>사진을 보정하기 위해 색상 과학자가 될 필요는 없습니다. Picu와 같은 온라인 도구를 포함하여 거의 모든 사진 편집 응용 프로그램에 있는 몇 가지 기본적인 슬라이더를 이해하기만 하면 됩니다.</p>
    
    <h3>1. 화이트 밸런스: 올바른 색온도 설정</h3>
    <p>화이트 밸런스는 모든 색 보정의 기초입니다. 그 역할은 사진에 "진정한 흰색"이 어떻게 보여야 하는지 알려주는 것입니다. 화이트 밸런스가 맞지 않으면 사진 전체에 부자연스러운 색조가 나타납니다. 일반적으로 두 가지 주요 슬라이더가 있습니다.</p>
    <ul>
        <li><strong>색온도:</strong> 이 슬라이더는 파란색과 노란색 사이의 색상 균형을 조정합니다. 텅스텐 조명 아래 실내에서 찍은 사진이 너무 주황색으로 보인다면, 색온도를 파란색 쪽으로 밀어 차갑게 만듭니다. 그늘에서 찍은 사진이 너무 파란색으로 보인다면, 노란색 쪽으로 밀어 따뜻하게 만듭니다.</li>
        <li><strong>색조:</strong> 이 슬라이더는 녹색과 마젠타 사이의 균형을 조정합니다. 자주 사용되지는 않지만, 형광등으로 인한 색조를 보정하는 데 중요합니다. 형광등은 종종 사진에 녹색조를 줄 수 있습니다.</li>
    </ul>
    <p><strong>사용 방법:</strong> 사진에서 중성색(흰색, 회색 또는 검은색)이어야 하는 것을 찾습니다. 해당 개체가 색조 없이 진정으로 중성으로 보일 때까지 색온도 및 색조 슬라이더를 조정합니다. 이렇게 하면 사진의 다른 모든 색상이 일반적으로 제자리를 찾습니다.</p>

    <h3>2. 노출, 대비, 하이라이트 및 그림자</h3>
    <p>이 슬라이더는 이미지의 톤 범위(밝기 및 어둡기)를 제어합니다. 깊이와 펀치를 추가하는 데 필수적입니다.</p>
    <ul>
        <li><strong>노출:</strong> 이것은 전체 이미지의 마스터 밝기 제어입니다. 사진 전체가 너무 어둡거나 너무 밝다면 여기에서 시작하십시오.</li>
        <li><strong>대비:</strong> 이것은 사진의 밝은 부분과 어두운 부분의 차이입니다. 대비를 높이면 어두운 부분이 더 어두워지고 밝은 부분이 더 밝아져 이미지에 "팝"을 더합니다. 대비를 낮추면 더 평평하고 부드러운 느낌을 줄 수 있습니다.</li>
        <li><strong>하이라이트:</strong> 이 슬라이더는 이미지의 가장 밝은 부분을 특별히 대상으로 합니다. 사진의 하늘이 너무 밝아서 흰색 덩어리처럼 보인다면, 하이라이트를 낮춰 파란색과 구름 디테일을 복구할 수 있습니다.</li>
        <li><strong>그림자:</strong> 이것은 하이라이트의 반대입니다. 이미지의 가장 어두운 부분을 특별히 대상으로 합니다. 사람의 얼굴이 그림자에 가려져 있다면, 그림자 슬라이더를 올려 얼굴 특징을 드러내면서 이미지의 나머지 부분을 너무 밝게 만들지 않을 수 있습니다.</li>
    </ul>

    <h3>3. 채도 및 생동감: 강도 제어</h3>
    <p>화이트 밸런스와 톤 범위가 설정되면 색상 자체의 강도를 조정할 수 있습니다.</p>
    <ul>
        <li><strong>채도:</strong> 이 슬라이더는 이미지의 모든 색상의 강도를 균일하게 증가시킵니다. 이 슬라이더는 매우 조심해서 사용하십시오! 너무 과도하게 사용하면 부자연스럽고 방사능처럼 보이는 색상과 얼룩덜룩한 피부 톤으로 이어지는 전형적인 초보자 실수입니다.</li>
        <li><strong>생동감:</strong> 이것은 채도의 "더 똑똑한" 버전입니다. 주로 이미지에서 가장 부드럽고 채도가 낮은 색상의 강도를 높이는 반면, 이미 채도가 높은 색상은 그대로 둡니다. 또한 피부 톤이 부자연스럽게 보이는 것을 방지하는 데 더 좋습니다. <strong>확실하지 않다면 채도 대신 생동감을 사용하십시오.</strong></li>
    </ul>

