    <h2>작업 도구: 힐링 및 복제</h2>
    <p>잡티를 제거하려면 주로 두 가지 유형의 도구를 사용합니다. 소프트웨어가 비파괴 편집을 허용하는 경우 별도의 레이어에서 이 작업을 수행하는 것이 가장 좋습니다.</p>

    <h3>1. 스팟 힐링 브러시 (당신의 가장 친한 친구)</h3>
    <ul>
        <li><strong>무엇인가:</strong> 이것은 가장 마법 같고 사용하기 쉬운 리터칭 도구입니다. 잡티를 클릭하기만 하면, 도구가 주변 픽셀(텍스처, 색상, 밝기)을 지능적으로 분석하고 자동으로 결함을 블렌딩하여 제거합니다.</li>
        <li><strong>사용 방법:</strong> 제거하려는 잡티보다 브러시를 약간 크게 만듭니다. 한 번 클릭하면 사라집니다. 대부분의 작고 고립된 점에는 이 도구만 있으면 됩니다. 빠르고 효과적이며 훌륭합니다.</li>
    </ul>

    <h3>2. 복제 스탬프 도구</h3>
    <ul>
        <li><strong>무엇인가:</strong> 복제 스탬프는 더 수동적인 도구입니다. 이미지의 한 영역(원본)에서 픽셀을 복사하여 다른 영역(대상)에 칠할 수 있습니다.</li>
        <li><strong>사용 방법:</strong> 먼저 키(종종 Alt 또는 Option)를 누른 상태에서 잡티 근처의 깨끗하고 질감이 좋은 피부 영역을 클릭하여 원본 영역을 정의해야 합니다. 그런 다음 브러시를 잡티 위로 이동하고 클릭하여 원본 픽셀을 그 위에 칠합니다.</li>
        <li><strong>언제 사용해야 하는가:</strong> 복제 스탬프는 스팟 힐링 브러시가 혼란스러워할 때, 예를 들어 입술 라인이나 눈썹과 같은 딱딱한 가장자리에 매우 가깝게 작업할 때 유용합니다. 자동 도구보다 더 정밀한 제어를 제공합니다.</li>
    </ul>

    <h2>피부 보정의 예술: 질감이 핵심</h2>
    <p>이것은 많은 초보자들이 가장 큰 실수를 저지르는 부분입니다. 피부의 자연스러운 질감을 모두 잃을 때까지 피부를 과도하게 부드럽게 만드는 것입니다. 실제 피부에는 모공이 있으며, 이를 완전히 지우면 가짜 같고 비전문적으로 보입니다.</p>

    <h3>잘못된 방법: 블러 도구</h3>
    <p>피부를 부드럽게 하기 위해 단순한 블러 도구를 사용하지 마십시오. 그것은 모든 것을 흐리게 만들어 질감을 파괴하고 그 끔찍한 플라스틱 같은 모습을 초래합니다.</p>

    <h3>올바른 방법: 주파수 분리(고급) vs. 질감 슬라이더(간단)</h3>
    <p><strong>주파수 분리</strong>는 포토샵에서 사용되는 고급 전문 기술입니다. 피부의 색상과 질감을 두 개의 다른 레이어로 분리하여, 미세한 모공 질감을 흐리게 하지 않고 색상과 톤 전환을 부드럽게 할 수 있습니다. 최고의 결과를 제공하지만 복잡한 워크플로우입니다.</p>
    <p>더 간단한 편집기를 사용하는 사람들에게는 <strong>질감</strong> 슬라이더가 현대적이고 효과적인 대안입니다.</p>
    <ul>
        <li><strong>질감 슬라이더:</strong> 많은 최신 편집기에는 이제 "질감" 또는 "선명도" 슬라이더가 포함되어 있습니다. 질감 슬라이더는 피부에 특히 유용합니다. 질감 슬라이더를 소량(예: -10 ~ -25) *줄임으로써* 피부를 부드럽게 하고 미세한 주름과 거친 부분의 모양을 줄일 수 있으며, 기본적인 모공 구조를 파괴하지 않습니다. 이것은 단순한 블러보다 훨씬 더 지능적이고 자연스러운 접근 방식입니다.</li>
    </ul>
    <p><strong>워크플로우:</strong> 먼저 힐링 브러시로 개별 잡티를 제거합니다. 그런 다음 얼굴 전체에 매우 미묘한 음의 질감 조정을 적용합니다. 도구가 허용하는 경우, 이 부드럽게 하는 효과를 피부에만 적용하도록 마스크를 사용하고, 선명하게 유지되어야 하는 눈, 눈썹, 입술은 피하십시오.</p>

    <h2>눈을 잊지 마세요</h2>
    <p>피부 작업을 마친 후, 눈에 약간의 주의를 기울이면 인물 사진이 생생해질 수 있습니다.</p>
    <ul>
        <li><strong>흰자위를 약간 밝게:</strong> 선택적 조정을 사용하여 눈의 흰자위를 약간 밝게 합니다. 순백색으로 만들지 말고, 약간 더 밝게 하여 황변이나 붉은기를 줄입니다.</li>
        <li><strong>홍채 선명하게:</strong> 눈의 홍채에만 소량의 선택적 선명화를 적용합니다. 이렇게 하면 초점이 생기고 피사체의 시선이 더 매력적으로 보입니다.</li>
    </ul>

