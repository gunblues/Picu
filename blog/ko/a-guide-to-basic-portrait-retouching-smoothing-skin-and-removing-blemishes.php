    <h2>철학: 지우지 말고 향상시키세요</h2>
    <p>어떤 도구를 만지기 전에 올바른 마음가짐을 갖는 것이 중요합니다. 목표는 플라스틱처럼 완벽한 인형을 만드는 것이 아닙니다. 목표는 일시적인 방해 요소를 제거하는 것입니다. 좋은 경험칙은 2주 후에는 사라질 것들만 제거하는 것입니다.</p>
