        <li><strong>유지할 것(또는 부드럽게만 할 것):</strong> 점, 흉터, 주름과 같이 그 사람의 성격의 일부인 영구적인 특징. 이것들을 지우면 부자연스럽게 보일 수 있으며, 심지어 피사체에게 불쾌감을 줄 수도 있습니다.</li>
