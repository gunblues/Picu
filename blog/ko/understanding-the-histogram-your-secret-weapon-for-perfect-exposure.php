    <h2>히스토그램이란 정확히 무엇인가?</h2>
    <p>256개의 수직 막대가 있는 막대 차트를 상상해 보십시오. 각 막대는 왼쪽 끝의 0(순수한 검은색)부터 오른쪽 끝의 255(순수한 흰색)까지 특정 밝기 수준을 나타냅니다. 차트의 중간은 중간 톤(중간 회색)을 나타냅니다.</p>
    <p>이제 히스토그램은 사진의 모든 픽셀을 통과하며 밝기를 결정합니다. 픽셀이 순수한 검은색이면 위치 0의 막대에 1을 추가합니다. 픽셀이 순수한 흰색이면 위치 255의 막대에 1을 추가합니다. 픽셀이 중간 회색이면 중간 막대에 1을 추가합니다.</p>
    <p>최종 그래프는 모든 밝기 수준에 걸쳐 픽셀의 분포를 보여줍니다. 어떤 지점에서든 그래프의 높이는 해당 밝기를 가진 사진의 픽셀 수를 나타냅니다. 요컨대, 히스토그램은 이미지의 톤에 대한 인구 조사입니다.</p>

    <h2>히스토그램 맵 읽는 방법</h2>
    <p>수평축이 가장 중요한 부분입니다. 세 가지 주요 영역으로 나뉩니다.</p>
    <ul>
        <li><strong>왼쪽 (그림자):</strong> 이 영역은 이미지의 어두운 픽셀을 나타냅니다. 그래프가 왼쪽 가장자리에 크게 뭉쳐 있다면, 사진에 순수한 검은색 영역이 있다는 의미입니다.</li>
        <li><strong>중간 (중간 톤):</strong> 균형 잡힌 사진의 대부분의 톤 정보가 일반적으로 여기에 있습니다. 이는 회색과 중간 범위의 색상을 나타냅니다.</li>
        <li><strong>오른쪽 (하이라이트):</strong> 이 영역은 밝은 픽셀을 나타냅니다. 그래프가 오른쪽 가장자리에 크게 뭉쳐 있다면, 순수한 흰색 영역이 있다는 의미입니다.</li>
    </ul>

    <h2>"절벽"의 위험: 클리핑 설명</h2>
    <p>히스토그램이 제공하는 가장 중요한 정보는 <strong>클리핑</strong>이 있는지 여부입니다. 클리핑은 그래프가 왼쪽 또는 오른쪽의 딱딱한 가장자리에 뭉쳐 있을 때 발생합니다.</p>
    <ul>
        <li><strong>그림자 클리핑 (검은색 뭉개짐):</strong> 그래프가 0(가장 왼쪽) 위치에 날카로운 스파이크 또는 "절벽"이 있다면, 상당수의 픽셀이 순수한 검은색으로 기록되었음을 의미합니다. 해당 영역의 모든 디테일은 손실되어 복구할 수 없습니다. 당신은 "검은색을 뭉개버린" 것입니다.</li>
        <li><strong>하이라이트 클리핑 (흰색 날아감):</strong> 그래프가 255(가장 오른쪽) 위치에 절벽이 있다면, 순수한 흰색 픽셀이 있다는 의미입니다. 이는 밝은 하늘이나 반사에서 흔히 발생합니다. 이 영역의 모든 디테일은 영원히 사라집니다. 당신은 "하이라이트를 날려버린" 것입니다.</li>
    </ul>
