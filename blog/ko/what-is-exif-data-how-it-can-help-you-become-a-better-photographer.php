    <p>디지털 카메라나 스마트폰으로 사진을 찍을 때마다, 이미지 자체와 함께 숨겨진 정보의 보물창고가 저장됩니다. 이 정보는 EXIF 데이터라고 불립니다. 많은 일반 사진작가들에게 이 데이터는 보이지 않고 사용되지 않습니다. 그러나 기술을 향상시키려는 사람들에게 EXIF 데이터는 사진에 대한 상세한 레시피 북과 같으며, 각 사진을 만드는 데 사용된 정확한 재료를 보여줍니다.</p>
