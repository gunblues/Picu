        <li><strong>화려한 글꼴이나 색상을 사용하지 마십시오:</strong> 간단하고 전문적인 글꼴을 고수하십시오. 색상은 모든 다른 사진에서 작동하도록 중성색(흰색, 검은색 또는 회색 음영)이어야 합니다.</li>
        <li><strong>중앙에 배치하지 마십시오(일반적으로):</strong> 일부 스톡 사진 에이전시는 구매 전에 사용을 방지하기 위해 중앙에 큰 워터마크를 배치하지만, 이것은 전문 포트폴리오에는 좋지 않습니다. 그것은 자신감 부족을 보여주고 시청자의 경험보다 도난에 대한 두려움을 우선시합니다.</li>
        <li><strong>구도를 잊지 마십시오:</strong> 사진 자체를 고려하십시오. 한 모서리가 매우 어둡고 다른 모서리가 매우 밝다면, 워터마크가 가장 읽기 쉽지만 여전히 미묘한 모서리를 선택하십시오.</li>
    </ul>

