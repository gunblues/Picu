    <h3>해야 할 일:</h3>
    <ul>
        <li><strong>간단하고 깔끔하게 유지:</strong> 워터마크는 읽기 쉬워야 하지만 압도적이지 않아야 합니다. 당신의 이름이나 웹사이트(예: "© John Smith Photography" 또는 "yourwebsite.com")가 있는 간단한 텍스트 줄 또는 로고의 깔끔한 단색 버전이 이상적입니다. 복잡하고 화려한 로고는 피하십시오.</li>
        <li><strong>반투명하게 만들기:</strong> 목표는 사진을 가리는 것이 아니라 보이게 하는 것입니다. 30%에서 60% 사이의 불투명도 수준이 일반적으로 좋은 범위입니다. 워터마크는 눈에 띄어야 하지만, 보는 사람이 가장 먼저 보는 것이 아니어야 합니다.</li>
        <li><strong>전략적으로 배치:</strong> 이미지의 모서리는 워터마크를 배치하기에 가장 일반적이고 효과적인 장소입니다. 모서리에 배치하면 주요 피사체로부터 주의를 덜 분산시킵니다. 워터마크가 사라질 수 있는 매우 복잡한 영역이나 도둑이 쉽게 복제할 수 있는 완전히 빈 영역(맑은 하늘과 같은)에 배치하는 것은 피하십시오. 주요 피사체 근처에 배치하되, 그 위에 배치하지 않는 것도 효과적일 수 있습니다.</li>
        <li><strong>일관성 유지:</strong> 모든 사진에 동일한 워터마크 디자인과 배치를 사용하십시오. 이 일관성은 브랜드 인지도를 구축하는 데 핵심입니다.</li>
    </ul>

    <h3>하지 말아야 할 일:</h3>
