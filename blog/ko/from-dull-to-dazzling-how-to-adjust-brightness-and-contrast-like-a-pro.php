    <p>이 가이드는 이러한 기본적인 조정을 명확히 할 것입니다. 기본적인 슬라이더뿐만 아니라 하이라이트 및 그림자와 같은 고급 도구도 탐색하여 이미지의 빛을 완전히 제어할 수 있는 기술을 제공합니다.</p>

    <h2>기초: 밝기와 대비</h2>
    <p>이 두 슬라이더는 사진 톤의 전체적인 모양을 제어하는 첫 번째이자 가장 중요한 도구입니다.</p>
    
    <h3>밝기:</h3>
    <ul>
        <li><strong>무엇인가:</strong> 밝기는 이미지의 모든 픽셀을 균일하게 밝게 또는 어둡게 만드는 간단하고 전역적인 조정입니다. 사진의 마스터 조명 스위치라고 생각하십시오.</li>
        <li><strong>언제 사용해야 하는가:</strong> 사진 전체가 노출 부족(너무 어둡거나) 또는 노출 과다(너무 밝거나)일 때 사용하십시오. 실내에서 사진을 찍었는데 모든 것이 약간 어둡게 보인다면, 밝기 슬라이더를 약간 움직이는 것이 첫 번째 단계입니다.</li>
        <li><strong>함정:</strong> 극단적인 조정은 조심하십시오. 어두운 사진에서 밝기를 너무 많이 높이면 가장 어두운 부분이 풍부한 검은색 대신 우유빛 회색으로 변하여 이미지가 색이 바랜 것처럼 보일 수 있습니다.</li>
    </ul>

    <h3>대비:</h3>
    <ul>
        <li><strong>무엇인가:</strong> 대비는 사진의 밝은 부분과 어두운 부분의 차이입니다. 대비를 높이면 밝은 픽셀은 더 밝아지고 어두운 픽셀은 더 어두워집니다.</li>
        <li><strong>언제 사용해야 하는가:</strong> 사진이 평평하거나 흐릿하게 보일 때 사용하십시오. 대비를 높이면 이미지가 더 선명하고 입체적으로 보입니다. 사진에 임팩트를 더하는 가장 빠른 방법 중 하나입니다.</li>
        <li><strong>함정:</strong> 대비가 너무 많으면 너무 적은 것만큼이나 나쁠 수 있습니다. 과도하게 대비된 이미지는 "검은색 뭉개짐"(어두운 영역의 모든 디테일이 순수한 검은색으로 손실됨) 및 "하이라이트 날아감"(밝은 영역의 모든 디테일이 순수한 흰색으로 손실됨)으로 고통받을 수 있습니다.</li>
    </ul>

    <h2>고급 도구: 하이라이트 및 그림자</h2>
    <p>밝기와 대비는 강력하지만, 둔한 도구이기도 합니다. 이들은 이미지 전체에 한 번에 영향을 미칩니다. 더 미묘한 제어를 위해서는 하이라이트 및 그림자 슬라이더를 사용해야 합니다. 이 도구는 톤 범위의 특정 부분을 대상으로 할 수 있습니다.</p>

    <h3>하이라이트:</h3>
    <ul>
        <li><strong>무엇인가:</strong> 하이라이트 슬라이더는 사진의 가장 밝은 부분을 특별히 대상으로 하며, 중간 톤과 그림자는 그대로 둡니다.</li>
        <li><strong>언제 사용해야 하는가:</strong> 이 도구는 밝은 하늘이 있는 사진에 생명줄입니다. 종종 카메라는 피사체에 노출을 맞추어 하늘이 밝고 디테일 없는 흰색 영역이 됩니다. 하이라이트를 낮추면 이미지의 나머지 부분을 어둡게 만들지 않고도 파란색과 구름 질감을 복구할 수 있습니다. 사람의 피부에 있는 눈부심을 줄이는 데도 좋습니다.</li>
    </ul>

    <h3>그림자:</h3>
    <ul>
        <li><strong>무엇인가:</strong> 그림자 슬라이더는 하이라이트의 반대입니다. 사진의 가장 어두운 부분을 특별히 대상으로 하며, 밝은 부분은 그대로 둡니다.</li>
        <li><strong>언제 사용해야 하는가:</strong> 이것은 역광 사진에 완벽합니다. 밝은 창문 앞에 서 있는 사람의 사진을 찍으면 얼굴이 깊은 그림자에 가려질 수 있습니다. 그림자 슬라이더를 올리면 얼굴의 밝기를 높이고 이미 밝은 창문을 날려버리지 않고도 특징을 드러낼 수 있습니다.</li>
    </ul>

