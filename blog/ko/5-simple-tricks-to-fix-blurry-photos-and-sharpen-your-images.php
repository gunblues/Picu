    <h2>먼저, 흐림의 종류를 이해하세요</h2>
    <p>모든 흐림이 똑같이 만들어지는 것은 아닙니다. 원인을 파악하면 현실적인 기대치를 설정하는 데 도움이 될 수 있습니다.</p>
    <ul>
        <li><strong>모션 블러:</strong> 노출 중에 카메라나 피사체가 움직일 때 발생하며 줄무늬나 고스팅 현상이 나타납니다. 완전히 수정하기 가장 어려운 유형입니다.</li>
        <li><strong>초점 이탈 흐림:</strong> 카메라 렌즈가 잘못된 지점(예: 사람 대신 배경)에 초점을 맞췄을 때 발생합니다.</li>
        <li><strong>일반적인 부드러움:</strong> 저품질 렌즈, 대기 안개 또는 이미지 크기를 줄이는 부작용으로 인해 발생할 수 있는 약간의 선명도 부족입니다. **이것이 수정하기 가장 쉬운 유형의 흐림입니다.**</li>
    </ul>
    <p>선명하게 하는 우리의 목표는 사진 내의 가장자리를 따라 대비를 향상시켜 *인식되는* 선명도를 높이는 것입니다. 새로운 디테일을 만들지는 않지만 기존 디테일을 훨씬 더 명확하게 만들 수 있습니다.</p>

    <h2>팁 1: 표준 선명화 필터 (주의해서 사용)</h2>
    <p>가장 일반적인 도구는 간단한 "선명하게" 슬라이더입니다. 뭉툭한 도구이지만 매우 신중하게 사용하면 효과적일 수 있습니다.</p>
    <p><strong>작동 방식:</strong> 표준 선명화 필터는 발견하는 모든 가장자리를 따라 밝은 픽셀과 어두운 픽셀 사이의 대비를 증가시킵니다. <br>
    <strong>사용 방법:</strong> 매우 작은 증분으로 선명화를 적용하십시오. 효과를 정확하게 판단하려면 100%로 확대하십시오. 목표는 가장자리를 선명하게 보이게 하는 것이지, 그 주위에 밝고 빛나는 후광을 만드는 것이 아닙니다. 후광이 보이면 너무 많이 적용한 것입니다. 이러한 이유로 많은 편집자들은 더 발전된 방법을 선호합니다.</p>

    <h2>팁 2: 더 많은 제어를 위한 "언샵 마스크"</h2>
    <p>혼란스러운 이름에도 불구하고 언샵 마스크(USM)는 더 정교하고 강력한 선명화 도구입니다. 정밀한 제어를 위해 세 가지 슬라이더를 제공합니다.</p>
    <ul>
        <li><strong>양 (또는 강도):</strong> 선명화의 강도를 제어합니다. 가장자리 픽셀이 얼마나 더 어두워지거나 밝아지는지를 결정합니다. (예: 50-150%).</li>
        <li><strong>반경:</strong> 영향을 받을 가장자리 주변 영역의 크기를 결정합니다. 미세한 디테일이 있는 사진에는 작은 반경(0.5-2 픽셀)이 가장 좋습니다. 선명화를 가장자리에 국한시키기 때문입니다. 반경이 크면 더 두껍고 뚜렷한 가장자리가 만들어집니다.</li>
        <li><strong>임계값:</strong> 이 슬라이더는 강한 가장자리가 없는 이미지 영역을 무시하도록 도구에 지시합니다. 임계값을 높이면 피부나 맑은 하늘과 같은 부드러운 영역을 선명하게 하는 것을 방지하여 도구가 원치 않는 노이즈나 입자를 증폭시키는 것을 막을 수 있습니다. 2-10의 임계값이 좋은 출발점입니다.</li>
    </ul>
    <p><strong>작업 흐름:</strong> 낮은 양, 약 1픽셀의 반경, 3의 임계값으로 시작하십시오. 후광을 만들지 않고 선명도가 눈에 띄게 향상될 때까지 양을 점차적으로 늘리십시오.</p>

    <h2>팁 3: 질감 또는 선명도 증가</h2>
    <p>많은 최신 사진 편집기에는 "질감" 또는 "선명도"라는 슬라이더가 있어 디테일을 향상시키는 더 지능적인 방법을 제공합니다.</p>
    <ul>
        <li><strong>선명도:</strong> 이미지의 중간 톤에 펀치를 더합니다. 사물을 더 극적이고 거칠게 보이게 하는 데 좋지만, 인물 사진에 과도하게 사용하면 거칠 수 있습니다.</li>
        <li><strong>질감:</strong> 매우 미세한 디테일을 대상으로 하는 더 세련된 도구입니다. 이미지의 더 큰 영역에 영향을 주지 않고 직물, 잎사귀 또는 건축물의 질감을 끌어내는 데 탁월합니다. 미묘한 선명화를 위해 종종 선명도보다 더 나은 선택입니다.</li>
    </ul>
    <p>질감 슬라이더를 위로 살짝 올려 이미지의 미세한 패턴을 어떻게 끌어내는지 확인하는 것으로 시작하십시오. 전통적인 선명화로 인한 후광 위험 없이 선명도를 더하는 좋은 방법입니다.</p>

    <h2>팁 4: 하이 패스 필터 (고급 기술)</h2>
    <p>이것은 전문 사진가들이 선호하는 기술로, 종종 Photoshop과 같은 소프트웨어에서 사용됩니다. 이미지의 복제 레이어를 만들고, 여기에 "하이 패스" 필터를 적용하여(가장자리를 분리함) 해당 레이어를 오버레이 또는 소프트 라이트 혼합 모드를 사용하여 원본과 다시 혼합하는 과정이 포함됩니다. 대부분의 온라인 도구에는 너무 복잡하지만, 가장 깨끗하고 제어된 선명화를 제공하므로 알아둘 가치가 있습니다.</p>

    <h2>팁 5: 선택적 선명화</h2>
    <p>이미지의 모든 부분이 선명할 필요는 없습니다. 인물 사진에서는 눈이 매우 선명하기를 원하지만 피부는 부드럽게 유지하고 싶을 수 있습니다. 도구에서 허용하는 경우 브러시나 마스크를 사용하여 선택적으로 선명화를 적용하십시오. 중요한 디테일(눈, 건물의 디테일, 꽃의 질감)을 선명하게 하고 다른 영역은 그대로 두십시오. 이 기술은 우리 눈이 자연스럽게 장면을 인식하는 방식을 모방하여 더 전문적이고 보기 좋은 이미지를 만듭니다.</p>

