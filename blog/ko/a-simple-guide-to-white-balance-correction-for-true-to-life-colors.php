    <h2>색온도 이해하기</h2>
    <p>화이트 밸런스 뒤에 숨겨진 핵심 개념은 <strong>색온도</strong>입니다. 다른 광원은 다른 색상의 빛을 생성합니다. 이 색상은 켈빈(K) 스케일이라는 척도로 측정됩니다.</p>
    <ul>
        <li><strong>따뜻한 빛 (낮은 켈빈):</strong> 촛불이나 전통적인 텅스텐 전구는 매우 따뜻하고 주황색-노란색 빛을 생성합니다. 이것은 스케일의 낮은 끝(약 1000-3000K)에 있습니다.</li>
        <li><strong>중성 빛 (한낮의 태양):</strong> 한낮의 직사광선은 비교적 중성 또는 "흰색" 빛으로 간주됩니다(약 5500K).</li>
        <li><strong>차가운 빛 (높은 켈빈):</strong> 심하게 흐린 날이나 그늘의 빛은 실제로 파란색 톤이거나 차갑습니다. 이것은 스케일의 높은 끝(약 6500-10,000K)에 있습니다.</li>
    </ul>
    <p>화이트 밸런스 설정의 역할은 광원의 색온도를 보정하여 중성 이미지를 생성하는 것입니다. 따뜻한 빛에서 촬영하는 경우, 카메라는 주황색을 중화하기 위해 파란색을 추가해야 합니다. 차가운 빛에서 촬영하는 경우, 카메라는 파란색을 중화하기 위해 노란색/주황색을 추가해야 합니다.</p>

    <h2>화이트 밸런스 보정 도구</h2>
    <p>사진 편집기에서는 일반적으로 화이트 밸런스를 조정하기 위한 세 가지 주요 도구를 찾을 수 있습니다.</p>

    <h3>1. 화이트 밸런스 프리셋</h3>
    <p>대부분의 편집기는 카메라에서 찾을 수 있는 설정과 일치하는 프리셋 드롭다운 메뉴를 제공합니다. 여기에는 "주광", "흐림", "그늘", "텅스텐", "형광등"과 같은 옵션이 포함됩니다. 사진이 촬영된 조명 조건을 알고 있다면, 해당 프리셋을 선택하는 것만으로도 즉시 올바른 결과에 매우 가깝게 만들 수 있습니다. 예를 들어, 실내 사진이 주황색으로 보인다면, "텅스텐" 프리셋을 선택하면 자동으로 파란색이 추가되어 상쇄됩니다.</p>

    <h3>2. 색온도 및 색조 슬라이더</h3>
    <p>이 슬라이더는 색상을 미세 조정하기 위한 수동 제어를 제공합니다.</p>
    <ul>
        <li><strong>색온도:</strong> 이것이 주요 슬라이더입니다. 파란색에서 노란색 축을 따라 색상을 조정합니다. 이미지가 너무 파란색이면 슬라이더를 노란색 쪽으로 이동하여 따뜻하게 만듭니다. 이미지가 너무 주황색이면 슬라이더를 파란색 쪽으로 이동하여 차갑게 만듭니다.</li>
        <li><strong>색조:</strong> 이 슬라이더는 녹색에서 마젠타 축을 따라 색상을 조정합니다. 이것은 더 특이한 광원, 특히 형광등으로 인한 색조를 보정하는 데 사용됩니다. 형광등은 종종 녹색조를 생성할 수 있습니다. 색온도를 보정했지만 사진이 여전히 약간 "이상하게" 보인다면, 색조 슬라이더를 약간 조정하는 것이 종종 해결책입니다.</li>
    </ul>

    <h3>3. 화이트 밸런스 선택기 (스포이드 도구)</h3>
    <p>이것은 화이트 밸런스를 설정하는 가장 빠르고 종종 가장 정확한 방법입니다. 스포이드 도구를 사용하면 소프트웨어에 중성 색상이어야 하는 것을 알려줄 수 있습니다.</p>
    <ol>
        <li><strong>도구 선택:</strong> 화이트 밸런스 패널에서 스포이드 아이콘을 찾아 선택합니다.</li>
        <li><strong>중성점 찾기:</strong> 사진에서 흰색, 중간 회색 또는 검은색과 같이 중성 색상이어야 한다고 확실히 아는 개체를 찾습니다. 흰색 셔츠, 회색 보도, 사람의 눈 흰자위 또는 가격표가 좋은 후보입니다.</li>
        <li><strong>중성점 클릭:</strong> 스포이드로 해당 중성점을 클릭합니다. 소프트웨어는 클릭한 픽셀의 색상을 자동으로 분석하고 해당 픽셀이 완벽하게 중성으로 되도록 색온도 및 색조 슬라이더를 즉시 조정합니다.</li>
    </ol>
    <p>소프트웨어는 이제 "진정한 중성"이 무엇인지 알기 때문에 이미지의 다른 모든 색상을 정확하게 다시 매핑하여 한 번의 클릭으로 사진 전체에서 색조를 제거할 수 있습니다. 이것은 강력하고 믿을 수 없을 정도로 효율적인 도구입니다.</p>

    <h2>간단한 화이트 밸런스 워크플로우</h2>
    <ol>
        <li><strong>먼저 스포이드 사용:</strong> 이미지에서 중성점을 스캔합니다. 찾을 수 있다면 스포이드 도구가 정확한 결과에 도달하는 가장 빠른 방법입니다.</li>
        <li><strong>중성점이 없으면 프리셋 사용:</strong> 사진에 명확한 중성 색상이 없는 경우(예: 일몰 또는 숲 장면), 기억하는 조명 조건에 따라 프리셋을 적용해 보십시오.</li>
        <li><strong>슬라이더로 미세 조정:</strong> 스포이드 또는 프리셋을 사용한 후, 색온도 및 색조 슬라이더를 사용하여 자신의 창의적인 판단에 따라 작고 최종적인 조정을 합니다. 창의적인 효과를 위해 장면을 약간 더 따뜻하거나 차갑게 만들고 싶을 수도 있습니다.</li>
