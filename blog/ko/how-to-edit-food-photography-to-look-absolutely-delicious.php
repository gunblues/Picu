    <p>인스타그램과 음식 블로그 시대에 음식 사진은 예술의 한 형태가 되었습니다. 우리는 입으로만 먹는 것이 아니라 눈으로 먼저 먹습니다. 훌륭한 음식 사진은 단순한 요리를 미식가의 걸작처럼 보이게 하여 보는 사람을 유혹하고 배를 꼬르륵거리게 만듭니다. 거부할 수 없는 음식 사진의 비결은 요리나 플레이팅에만 있는 것이 아닙니다. 바로 편집에 있습니다. 올바른 편집 기술은 평평하고 식욕을 돋우지 않는 스냅샷을 생생하고 질감 있으며 절대적으로 맛있어 보이는 이미지로 바꿀 수 있습니다.</p>
