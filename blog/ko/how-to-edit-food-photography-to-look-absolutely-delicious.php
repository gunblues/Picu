    <h2>1. 밝고 통풍이 잘 되는 것이 보통 옳다: 노출 조정</h2>
    <p>어둡고 분위기 있는 사진은 일부 음식(예: 진한 초콜릿 케이크)에는 잘 어울리지만, 일반적으로 음식은 밝고 조명이 잘 되어 있을 때 가장 식욕을 돋웁니다. 이는 신선함과 청결함을 전달합니다.</p>
